/** Описание времени суток: 0 — день, 1 — ночь */
const pick = <T,>(a: T[], r: () => number): T => a[Math.floor(r() * a.length)]

export function phrase(o: { style: string; culture: string; state: string; gov: string; role: Role; night: number; rnd: () => number }): string {
  const pool = GROUPS[o.style] ?? GROUPS[o.culture] ?? EMPIRE
  const lines: string[] = [...pool.any]
  const byRole = pool[o.role]
  if (byRole) lines.push(...byRole, ...byRole) // роль весомее общих фраз
  if (o.night > 0.35 && pool.dusk) lines.push(...pool.dusk, ...pool.dusk)
  for (const g of GOV) if (g.re.test(o.gov)) lines.push(...g.lines)
  const s = o.state || 'здешних краях'
  return pick(lines, o.rnd).replace(/\{s\}/g, s)
}
