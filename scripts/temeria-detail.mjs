// Королевство Темерия на карте: Вызима (столица, бывш. Ливинштейн), Дориан (бывш. Вальельдорф), Бренна (бывш. Целгард) — города;
// описания всех поселений, места (Дом Порога, Дверь Фольтеста, Битва у Дориана, Сожжённый Брукталь, Сход у Бренны), походы Восстания Защиты.
// Запуск после gareford-detail.mjs: node scripts/temeria-detail.mjs
import { readFileSync, writeFileSync } from 'fs'
import { TM_NAMES, STATE } from './lore/temeria.mjs'

const WORLD = 'resources/default-world/world.json'
const world = JSON.parse(readFileSync(WORLD, 'utf8'))
const YEAR = world.calendar.months.reduce((s, m) => s + m.days, 0)
const D = (y) => Math.round((y - 1) * YEAR)
let seed = 20261110
const rnd = () => ((seed = (Math.imul(seed, 1664525) + 1013904223) >>> 0) / 4294967296)
const pick = (a) => a[Math.floor(rnd() * a.length)]
const chance = (p) => rnd() < p
const st = world.states.find((s) => s.base.name === STATE)
const admin = new Map(world.adminRegions.map((a) => [a.id, a]))

// переименования: города стоят на месте прежних городков; округ, названный по городку, получает новое имя
const CITIES = [
  { id: 1726, old: 'Ливинштейн', name: 'Вызима', type: 'city' },
  { id: 1715, old: 'Вальельдорф', name: 'Дориан', type: 'city' },
  { id: 1831, old: 'Целгард', name: 'Бренна', type: 'city' }
]
for (const c of CITIES) {
  const p = world.provinces.find((x) => x.id === c.id)
  const area = admin.get(p.areaId)
  if (area?.name === `Округ ${c.old}`) area.name = `Округ ${c.name}`
  p.name = c.name
  p.settlement = { ...(p.settlement ?? { x: p.x, y: p.y }), type: c.type }
}

const provs = world.provinces.filter((p) => p.owners?.at(-1)?.[1] === st.id)
const byName = (nm) => provs.find((p) => p.name === nm)
const sx = (p) => p.settlement ?? p
const landOf = (p) => `${admin.get(p.areaId)?.name ?? ''}`
const person = (women) => `${pick(women ? TM_NAMES.women : TM_NAMES.men)} ${pick(TM_NAMES.families)}`

// какому Очагу принадлежит округ
const HEARTH = {
  'Округ Грюненау': 'дом Лауэн', 'Округ Висау': 'дом Висау', 'Округ Вызима': 'королевский дом Темерских', 'Округ Дориан': 'дом Дориан', 'Округ Тальау': 'дом Тальау',
  'Округ Бренна': 'дом Бренна', 'Округ Зонельштейн': 'дом Зонельштейн', 'Округ Висинау': 'Орден Открытой Двери', 'Округ Эльмбург': 'дом Эльмбург'
}
const FARM = ['хмель и ячмень', 'рожь и лён', 'овец и сыр', 'пасеки и яблони', 'репу и капусту', 'коров и масло']
const TIMBER = ['рубят лес для плотов', 'гонят дёготь и смолу', 'жгут уголь', 'делают бочки и клёпку', 'вяжут плоты для сплава']
const NOTE = [
  'Над дверью каждого дома вырезано слово «Постучи»: так в Темерии говорят и гостю, и просящему.',
  'У околицы стоит миска на столбе: для тех, кто пришёл ночью и не хочет будить хозяев.',
  'В Ночь Дверей здесь до рассвета держат двери открытыми, а староста вписывает в Книгу Крова тех, кто пришёл.',
  'Староста помнит, кто и когда получил кров, и спросит гостя имя прежде, чем налить ему супа.',
  'На сельской площади висит колокол Привратников: в него бьют, когда на границе замечены чужие.',
  'Дети здесь играют в «просящих и привратников»: один стучит, другой решает — открывать или нет.',
  'Деревенские считают, что Тёмный год не придёт, пока в окне горит свет, и ставят свечи на подоконник.',
  'Ночью по дороге часто проходят неизвестные с узлами: утром на лавке остаётся горбушка и записка «Спасибо».'
]

let n = 0
for (const p of provs.filter((x) => x.settlement)) {
  const t = p.settlement.type
  const hearth = HEARTH[landOf(p)] ?? ''
  const lines = []
  if (p.name === 'Вызима') {
    lines.push('Вызима — столица Темерии: город на пересечении лесных дорог с широкой площадью и каменным Домом Порога, где висит дубовая Дверь Фольтеста. По обычаю, на каждый день года здесь накрыт стол для тех, кто постучит.')
    lines.push('Правит король Фольтест Темерский; в Доме Порога заседает Совет Пяти Ключей, а в подвале лежит Книга Крова. Над крышами стоят печные башни — «Очаги», дымящие круглый год, чтобы с дороги было видно, где ждут.')
  } else if (p.name === 'Дориан') {
    lines.push('Дориан — город лесных общин на старой имперской дороге, где в 978 г. Зигфрид Висау и охотники разбили отряд Республики. По праву места здесь держат Очаг дома Дориан; топор на их гербе вырезан и на каждых воротах.')
    lines.push('Ярмарки в Дориане идут три раза в год: сюда приходят соляные обозы Чеафарала и плоты с лесом.')
  } else if (p.name === 'Бренна') {
    lines.push('Бренна — город потомков беглых кандальных: тёмные дома из камня, кузницы и рынок. На ратуше висит порванная цепь — герб дома Бренна. Здесь в 977 г. дворы и общины выбрали Фольтеста военным вождём, а в 979-м дом закрыл ему дверь.')
    lines.push('В Бренне живёт легат Валериан Корд, и сюда смотрит Рейх: город бурлит от слухов и от молодых людей с цепью на шее.')
  } else if (p.name === 'Висинау') {
    lines.push('Висинау — святыня Ордена Открытой Двери: большой храм с воротами без створок и приютами на каждом углу. Здесь сидит Верховный привратник, отсюда расходятся привратники по дорогам.')
  } else if (p.name === 'Висау') {
    lines.push('Висау — замок дома Висау на границе с Кагией: низкие стены, высокие башни, склады копий. Здесь живут потомки дезертиров и лучшие копейщики Дружины Порога.')
  } else if (p.name === 'Эльмбург') {
    lines.push('Эльмбург — пограничная башня над лесом, что смотрит на Рейх и Кагию. Комендант — Агнес Висау; под башней стоит каменный дом Эльмбургов, где пишут и считают.')
  } else if (p.name === 'Брукталь') {
    lines.push('Брукталь — деревня, сожжённая Республикой в 977 г.: тридцать домов, девятнадцать убитых. Новые избы стоят чуть в стороне, а на пепелище — столб, который никто не решается убрать. Староста Геро помнит каждый дом.')
  } else if (t === 'city') {
    lines.push(`${p.name} — город Темерии с рынком, ратушей и Очагом на площади.`)
  } else if (t === 'town') {
    lines.push(`${p.name} — городок земель ${hearth || 'королевства'}: ратуша с колокольней, рынок и дом хозяина, а над ним — печная башня «Очаг». Живут ${pick(['пивом и хмелем', 'лесом и сплавом', 'сукном и мельницами', 'перевалочным торгом'])}.`)
    lines.push(`Писарь — ${person()}; Хранитель Крова присылает сюда раз в год проверку Книги.`)
    lines.push(pick(NOTE))
  } else if (t === 'castle' || t === 'tower') {
    lines.push(`${p.name} — застава Дружины Порога: башня, казарма и ворота без створок для просящих. Комендант — ${person(chance(0.3))}.`)
  } else if (t === 'temple') {
    lines.push(`${p.name} — храм Ордена Открытой Двери с приютом при нём.`)
  } else if (p.terrain === 2 || p.terrain === 6) {
    lines.push(`${p.name} — лесная деревня: ${pick(['дома из тёмного дуба', 'избы с высокими крышами', 'сруб с лесопилкой'])}, делянки и запань на реке. ${pick(TIMBER).replace(/^./, (c) => c.toUpperCase())} и выращивают ${pick(FARM)}.`)
    lines.push(`Староста — ${person(chance(0.3))}.`)
    lines.push(pick(NOTE))
  } else if (p.terrain === 3 || p.terrain === 4 || p.terrain === 5) {
    lines.push(`${p.name} — холмистая деревня: каменные дома, пастбища и сыроварня; держат ${pick(FARM)}.`)
    lines.push(`Староста — ${person(chance(0.3))}.`)
    lines.push(pick(NOTE))
  } else {
    lines.push(`${p.name} — деревня на равнине: ${pick(['белёные дома с чёрными балками', 'мельница на ручье и пекарня', 'красные крыши и колодец'])}. Здесь выращивают ${pick(FARM)}.`)
    lines.push(`Староста — ${person(chance(0.3))}.`)
    lines.push(pick(NOTE))
  }
  lines.push(`${landOf(p)}${hearth ? `; земли ${hearth}` : ''}.`)
  p.description = lines.join(' ')
  n++
}

// ---------- места ----------
const place = (id, name, type, at, from, description, stateId = '', off = [14, 10], ruler = '') => {
  const old = world.places.find((p) => p.id === id)
  world.places = world.places.filter((p) => p.id !== id)
  world.places.push({ id, mapId: 'world', x: Math.round(at.x) + off[0], y: Math.round(at.y) + off[1], ...(old?.innerMapId ? { innerMapId: old.innerMapId } : {}), base: { name, type, stateId, population: '', ruler, image: '', description }, history: [], from: from == null ? null : D(from), to: null })
}
const cap = byName('Вызима'), dor = byName('Дориан'), bren = byName('Бренна'), bruk = byName('Брукталь'), vis = byName('Висинау'), elm = byName('Эльмбург'), gruen = byName('Грюненау')
place('lore-tm-capital', 'Вызима', 'capital', sx(cap), null, '**Столица Темерии.** Дом Порога, Совет Пяти Ключей, Книга Крова и Дверь Фольтеста; на каждый день года накрыт стол для просящих.', st.id, [0, 0], 'Король Фольтест Темерский')
place('lore-tm-houseofdoor', 'Дом Порога', 'landmark', sx(cap), 979.4, '**Дворец и архив.** Каменный дом с дубовой дверью: здесь заседает Совет Пяти Ключей и хранится Книга Крова.', '', [-16, -12])
place('lore-tm-door', 'Дверь Фольтеста', 'landmark', sx(cap), 977.9, '**Дубовая дверь первого приюта.** Замка на ней нет с тех пор, как первый беглец выломал его.', '', [16, -12])
if (dor) place('lore-tm-dorian', 'Битва у Дориана', 'battle', sx(dor), 978.5, '**978.5.** Зигфрид Висау и лесные общины разбили в чаще отряд Республики; обоз и знамёна взяты.', '', [14, 12])
if (bruk) place('lore-tm-brukburn', 'Сожжённый Брукталь', 'battle', sx(bruk), 977.7, '**977.7.** Республика сожгла деревню по списку, составленному Эльмбургами: тридцать домов, девятнадцать убитых.', '', [14, -12])
if (bren) place('lore-tm-brennagather', 'Сход у Бренны', 'landmark', sx(bren), 977.9, '**977.9.** Дворы и общины собрались у Бренны и выбрали Фольтеста военным вождём.', '', [-14, 12])
if (vis) place('lore-tm-visinau', 'Храм Висинау', 'temple', sx(vis), null, '**Святыня Ордена Открытой Двери.** Ворота без створок и приюты на каждом углу.', '', [14, 10])
if (elm) place('lore-tm-elmtower', 'Эльмбургская башня', 'landmark', sx(elm), null, '**Пограничная башня** на Рейх и Кагию: дозор и каменный дом Эльмбургов.', '', [14, -10])
if (gruen) place('lore-tm-path', 'Начало Тропы Крова', 'landmark', sx(gruen), 302, '**Тайный путь беглых.** Отсюда при Империи уводили беглых от Грюненау до Эльмбурга.', '', [-14, 10])

// ---------- походы ----------
world.armies = (world.armies ?? []).filter((a) => !a.id.startsWith('lore-army-tm-'))
const pt = (p, y) => { const s = sx(p); return { x: Math.round(s.x), y: Math.round(s.y), date: D(y) } }
if (bren && dor && cap) world.armies.push({ id: 'lore-army-tm-978', name: 'Ополчение Фольтеста (977–979)', mapId: 'world', stateId: st.id, color: '#d8b84a', waypoints: [pt(bren, 977.9), pt(dor, 978.5), pt(cap, 979.1)] })
if (bruk && cap && elm) world.armies.push({ id: 'lore-army-tm-republic', name: 'Отряд Республики (977–979)', mapId: 'world', stateId: world.states.find((s) => s.base.name === 'Республика')?.id ?? '', color: '#a04a3a', waypoints: [pt(bruk, 977.6), pt(cap, 978.2), pt(elm, 979.2)] })

writeFileSync(WORLD, JSON.stringify(world, null, 1))
const cnt = {}
for (const p of provs) if (p.settlement) cnt[p.settlement.type] = (cnt[p.settlement.type] ?? 0) + 1
console.log(`Темерия: описаний ${n}, по типам ${JSON.stringify(cnt)}`)
