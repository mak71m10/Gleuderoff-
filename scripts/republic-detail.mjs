const lib = liberation(world.provinces, (p) => admin.get(admin.get(p.areaId)?.parentId)?.name)
const MARK = '**Освобождение (977).**'
let freed = 0
for (const p of world.provinces) {
  if (!p.owners.some(([, o]) => o === rep.id)) continue
  const c = lib(p)
  if (!c) continue
  const month = world.calendar.months[Math.min(4, Math.floor((c.date % 1) * 5))].name
  const after = p.owners.find(([d, o]) => d > D(978) && o !== rep.id)
  const line = `${MARK} ${month} ${Math.floor(c.date)} г.: ${c.how} — ${c.force}${c.merge ? `; в Республику вошёл по Акту о единении` : ''}.${after ? ` Ушёл из Республики в ${Math.floor(after[0] / YEAR) + 1} г. — к ${stateById.get(after[1])?.base.name ?? 'соседям'}.` : ''}`
  const base = (p.description ?? '').split('\n\n').filter((x) => !x.startsWith(MARK)).join('\n\n')
  p.description = base ? `${base}\n\n${line}` : line
  freed++
}

// ---------- смена власти по годам ----------
rep.history = (rep.history ?? []).filter((h) => !String(h.id).startsWith('lore-rp-'))
rep.history.push(
  { id: 'lore-rp-provisional', date: D(976.9), patch: { government: 'Временное правительство (Декларация Тиррита)', ruler: 'Глава Временного правительства Максимилиан фон Эрлах', rulerTitle: 'Глава Временного правительства', rulerId: 'lore-rp-chancellor' } },
  { id: 'lore-rp-constituent', date: D(977.86), patch: { government: 'Учредительное собрание (Клуб Вольного Огня); Охота за имперцем', ruler: 'Председатель собрания Йорг Фламм', rulerTitle: 'Председатель собрания', rulerId: 'lore-rp-flamm' } },
  { id: 'lore-rp-charter', date: D(978.92), patch: { government: rep.base.government, ruler: rep.base.ruler, rulerTitle: 'Канцлер', rulerId: 'lore-rp-chancellor' } }
)

writeFileSync(WORLD, JSON.stringify(world, null, 1))
console.log(`Республика: описаний поселений ${made}, строк «Освобождение» ${freed}, особых мест ${world.places.filter((p) => p.id.startsWith('lore-rp-')).length}`)
