  Филь: 'Порт на гарефордской границе, город Мелькеров: новые дома из жёлтого кирпича, контора дальних дымов, где писцы записывают семьи за границей, и большой рынок сукна. Здесь богаче, чем в Авеле, и все об этом знают.',
  Росдорф: 'Хлебный город Розенов на границе Олекохта: амбары на сваях, тракт, по которому каждую весну уходит обоз в Элву. С 1008 г. возницы ходят только днём и только вдвоём.',
  Ливенхайм: 'Замок рыцарей Ливен на холме — старая имперская кладка, флаг с белой башней. Здесь держат свои дымы здешние — имперские крестьяне; в Зимний переход 987 г. к ним пришли семь сотен дворов.',
  Тальинведель: 'Храм Дома Света у Росдорфа: в нём горит Свеча Дороги, которую зажигают в День Ворот за всех, кто уходит, и молятся о тех, кто остался за границей.',
  Дорненвальд: 'Сторожевая башня на гарефордской границе: на её верху каждый вечер жгут сигнальный дым — по нему видно, что граница спокойна.',
