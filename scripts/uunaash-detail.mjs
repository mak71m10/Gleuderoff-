const CROP = ['рожь и овёс', 'лён и шерсть', 'железо и уголь', 'рыбу и соль', 'лес и смолу', 'коз и сыр', 'ячмень и пиво', 'сукно']

let n = 0
for (const p of provs.filter((x) => x.settlement)) {
  const t = p.settlement.type
  const lines = []
  const lord = lordOf(p)
  const loc = lord === 'Ливен'
  if (SPECIAL[p.name]) {
    const kind = { city: 'город', town: 'город', port: 'порт', castle: 'замок', temple: 'храм', tower: 'башня' }[t] ?? 'село'
    lines.push(`${p.name} — ${p.name === 'Авель' ? 'столица Княжества Уунааш' : `${kind} Уунааша`}.`)
    lines.push(SPECIAL[p.name])
  } else if (['town', 'port'].includes(t)) {
    lines.push(`${p.name} — ${t === 'port' ? 'гавань' : 'городок'} Уунааша: каменные дома под тёмной черепицей, меняльная лавка, храм Дома Света. Живут ${pick(CROP)}.`)
    lines.push(pick(NOTE))
  } else {
    lines.push(`${p.name} — ${t === 'fishing' ? 'рыбацкое село' : 'село'}${loc ? ' здешних' : ''}: ${pick(['низкие дома под снегом, трубы выше крыш', 'дворы вдоль дороги, у каждого — поленница до окон', 'дома вокруг колодца и храмовой часовни', 'хутора на склоне, дымы видно за три версты'])}; живут ${pick(CROP)}.`)
    lines.push(`Староста — ${loc ? local() : person(chance(0.3))}.`)
    lines.push(pick(NOTE))
  }
  lines.push(`Дымы приписаны к Дому ${lord}. ${areaOf(p)}, ${landOf(p)}; ${loc ? 'здешние (имперцы)' : chance(0.3) ? 'уунаашевцы и здешние' : 'уунаашевцы'}.`)
  p.description = lines.join(' ')
  n++
}

const place = (id, name, type, at, from, description, stateId = '', off = [14, 10], ruler = '') => {
  const old = world.places.find((p) => p.id === id)
  world.places = world.places.filter((p) => p.id !== id)
  world.places.push({ id, mapId: 'world', x: Math.round(at.x) + off[0], y: Math.round(at.y) + off[1], ...(old?.innerMapId ? { innerMapId: old.innerMapId } : {}), base: { name, type, stateId, population: '', ruler, image: '', description }, history: [], from: from == null ? null : D(from), to: null })
}
world.places = world.places.filter((p) => !p.id.startsWith('lore-uu-'))
const cap = byName('Авель')
place('lore-uu-capital', 'Авель', 'capital', sx(cap), 977.2, '**Столица.** Бывший Брасенхольм. Стена Ключей у главных ворот, Палата Ворот с Книгой Дымов, князь Абрам Яффе.', st.id, [0, 0], 'Князь Абрам Яффе')
place('lore-uu-wall', 'Стена Ключей', 'landmark', sx(cap), 977.2, '**Святыня.** Четыре тысячи ключей от домов, оставленных в Империи; первый — Самуила Яффе, от дома в Аурхафене. В День Ворот здесь ставят Книгу Дымов, и люди несут мимо горшки с углями.', '', [16, -12])
place('lore-uu-winter', 'Зимний переход', 'battle', sx(cap), 987.6, '**987.6.** Голодный День Ворот: треть дымов страны ушла к тем, у кого было зерно. Книга Дымов закрыта на год, князь правил с Ключниками.', '', [-16, 12])
const ros = byName('Росдорф')
if (ros) place('lore-uu-grain', 'Хлебная дорога', 'landmark', sx(ros), 987.7, '**Тракт на Олекохт.** Каждую весну Иосиф Розен ведёт отсюда обоз с зерном в Элву, к валлинам. С 1008 г. на тракте Мороки: двое возниц пропали.', '', [14, -12])
const fil = byName('Филь')
if (fil) place('lore-uu-far', 'Контора дальних дымов', 'landmark', sx(fil), 1001, '**Филь.** Писцы Мелькера записывают сюда семьи из общин Империи и Гарефорда; за год — до тысячи дальних дымов.', '', [14, 12])
const lay = byName('Лаяно')
if (lay) place('lore-uu-stone', 'Камень Давида', 'landmark', sx(lay), 1004.8, '**Мол Лаяно.** Памятный камень наследнику Давиду Яффе, утонувшему с когом у Артензи’Винара в 1004 г.', '', [-14, 12])
if (lay) place('lore-uu-raid996', 'Морские псы у Лаяно', 'battle', sx(lay), 996.5, '**996.5.** Налётчики Креита жгут когов Дома Тальман у мола.', '', [16, 14])
const liv = byName('Ливенхайм')
if (liv) place('lore-uu-oath', 'Присяга здешних', 'landmark', sx(liv), 983, '**983 г.** Рыцарь Конрад фон Ливен присягает князю за право имперских крестьян держать свои дымы.', '', [14, 12])

world.armies = (world.armies ?? []).filter((a) => !a.id.startsWith('lore-army-uu-'))
const pt = (p, y) => { const s = sx(p); return { x: Math.round(s.x), y: Math.round(s.y), date: D(y) } }
const ain = byName('Айно')
const south = provs.filter((p) => p.neighbors.some((nb) => world.provinces.find((q) => q.id === nb)?.owners?.at(-1)?.[1] === world.states.find((s) => s.base.name === 'Княжества Гарефорда')?.id))[0]
if (south && cap) world.armies.push({ id: 'lore-army-uu-976', name: 'Исход общин на север (976–977)', mapId: 'world', stateId: st.id, color: '#1f3a6a', waypoints: [pt(south, 976.6), ...(fil ? [pt(fil, 976.8)] : []), pt(cap, 977.2)] })

writeFileSync(WORLD, JSON.stringify(world, null, 1))
console.log(`Уунааш: описаний ${n}, мест ${world.places.filter((p) => p.id.startsWith('lore-uu-')).length}`)
