// Слово для области (среднего уровня) по культуре: «Херад Скогвик», «Курень Златов»
const AREA_WORD = {
  imperial: 'Округ', church: 'Приход', romance: 'Дистретто', kaltrans: 'Кантон', nordic: 'Херад', dwarven: 'Чертог',
  eluin: 'Круг', eleon: 'Дом', elven: 'Чаща', yut: 'Уезд', desert: 'Вилайет', dark: 'Пустошь', zlatay: 'Курень',
  orcish: 'Стоянка', cin: 'Уезд'
}

export function makeNamer(seed = 1) {
  let s = seed >>> 0
  const rnd = () => ((s = (Math.imul(s, 1664525) + 1013904223) >>> 0) / 4294967296)
  const pick = (arr) => arr[Math.floor(rnd() * arr.length)]
  const used = new Set()
  const cap = (w) => w.charAt(0).toUpperCase() + w.slice(1)
  const fix = (w) =>
    cap(
      w
        .replace(/--/g, '-')
        .replace(/-$/, '')
        .replace(/([аеиоуыэюя])\1/g, '$1')
        .replace(/-([а-яё])/g, (m, c) => '-' + c.toUpperCase())
    )

  function base(culture) {
    const st = STYLE[culture] ?? STYLE.imperial
    for (let t = 0; t < 60; t++) {
      let w = pick(st.a) + pick(st.b) + pick(st.c)
      if (culture === 'yut' && rnd() < 0.5) w = pick(st.a) + pick(st.b).toLowerCase() + pick(st.b) + pick(st.c)
      w = fix(w)
      if (w.replace(/[^а-яё]/gi, '').length < 4) continue
      if (!used.has(w)) {
        used.add(w)
        return w
      }
    }
    // запасной вариант — добавить приставку «Верхний/Нижний…»
    const w = fix(pick(st.a) + pick(st.b) + pick(st.c))
    const pref = pick(['Верхний ', 'Нижний ', 'Старый ', 'Новый ', 'Малый ', 'Большой '])
    let n = 2
    while (used.has(`${pref}${w}${n > 2 ? ' ' + n : ''}`)) n++
    const out = `${pref}${w}${n > 2 ? ' ' + n : ''}`
    used.add(out)
    return out
  }

  // «Альтенбург» -> «Альтенбургская марка»: прилагательное из основы
  function adjective(word) {
    const stem = word.replace(/[ьйаяоеиыуюэ]$/i, '').replace(/-/g, '')
    return stem + (/[кгх]$/.test(stem) ? 'ская' : 'ская')
  }

  return {
    province: (culture) => base(culture),
    area: (culture, provinceName) => `${AREA_WORD[culture] ?? 'Округ'} ${provinceName}`,
    region: (culture) => {
      const st = STYLE[culture] ?? STYLE.imperial
      const end = pick(st.region)
      const w = fix(pick(st.a) + pick(st.b))
      let name
      if (end.startsWith('-')) name = w + end
      else if (end.startsWith('ск') || end.startsWith('ая') || end.startsWith('ие') || end.startsWith('ий')) name = w + end
      else name = w + end
      name = fix(name)
      let n = 2
      let out = name
      while (used.has(out)) out = `${name} ${n++}`
      used.add(out)
      return out
    }
  }
}
