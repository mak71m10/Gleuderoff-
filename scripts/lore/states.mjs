// Сведения о государствах из ответов автора (вопросы 14–31). Только то, что автор сказал;
// придуманное помечено в тексте «(черновик)».
export default function states({ world, Y, reigns }) {
  const byName = new Map(world.states.map((s) => [s.base.name, s]))
  const S = (name, fields, extra = {}) => {
    const st = byName.get(name)
    if (!st) {
      console.warn(`Нет государства «${name}»`)
      return null
    }
    Object.assign(st.base, fields)
    Object.assign(st, extra)
    return st
  }
  const H = (layout, colors, emblem, emblemColor) => ({ layout, colors, emblem, emblemColor })
  const empire = byName.get('Империя')
  const church = byName.get('Святая церковь')

  // --- Империя и её прямые вассалы ---
  S(
    'Империя',
    {
      fullName: 'Империя Монстаргов',
      government: 'Парламентская монархия (власть Верховного совета)',
      rulerTitle: 'Князь',
      rulerId: '',
      ruler: 'Князья Дагерфорда (имена утеряны)',
      dynastyId: 'lore-monstarg',
      religionId: 'lore-house-light',
      culture: 'Имперцы',
      stability: 30,
      heraldry: H('plain', ['#7a1420'], 'dragon', '#111111'),
      description:
        'Наследница державы Тейбера I, когда-то объединявшей весь центральный континент Лору. После эпохи раздоров и гражданской войны (975–980) потеряла около 80% земель; нынешняя Империя — те самые «последние 20%». Власть у Верховного совета, императорская семья заперта в Дистрикте Альфа. Империя в стагнации: «не развивается и не умирает». Прямые вассалы — Корона Аргус, Графство Мангениум и Великое Герцогство Штирия; они не часть Империи, но подчиняются имперскому совету. С Республикой Империя борется за влияние во всех государствах пост-имперского пространства.'
    },
    { from: null }
  )
  if (empire) {
    // Правители Империи во времени + название «Королевство Дагерфорд» до 150 г.
    empire.history = reigns.map((r, i) => ({
      id: `lore-reign-${i}`,
      date: Y(r.year),
      patch: { rulerId: `lore-${r.rulerId}`, rulerTitle: r.title, ...(r.year === 130 ? { name: 'Королевство Дагерфорд', government: 'Абсолютная монархия' } : {}), ...(r.year === 122 ? { government: 'Регентство' } : {}), ...(r.year === 150 ? { name: 'Империя', government: 'Империя (абсолютная монархия)' } : {}) }
    }))
    // до переворота Тейбера — одно из княжеств центра Лоры
    empire.history.unshift({ id: 'lore-reign-princedom', date: Y(-10000), patch: { name: 'Княжество Дагерфорд', government: 'Военизированное княжество', heraldry: H('bicolor-h', ['#5a1a1a', '#1a1a1a'], 'sword', '#c9a45c') } })
    empire.history.push({ id: 'lore-reign-council', date: Y(980), patch: { government: 'Парламентская монархия (власть Верховного совета)' } })
    empire.history.push({ id: 'lore-reign-lutsiy', date: Y(940), patch: { government: 'Абсолютная монархия (Люций Кровавый)' } })
    empire.history.push({ id: 'lore-reign-robert', date: Y(170), patch: { government: 'Империя (монарх и Верховный совет)' } })
    empire.base.name = 'Империя'
  }
  for (const [name, house, ruler, title] of [
    ['Корона Аргус', 'lore-house-argus', 'lore-argus-now', 'Король'],
    ['Графство Мангениум', 'lore-house-mangenium', 'lore-mangenium-now', 'Графиня'],
    ['Великое Герцогство Штирия', 'lore-house-styria', 'lore-styria-now', 'Великий герцог']
  ]) {
    S(name, {
      overlordId: empire?.id ?? '',
      dynastyId: house,
      rulerId: ruler,
      rulerTitle: title,
      religionId: 'lore-house-light',
      culture: 'Имперцы',
      government: 'Монархия, прямой вассал Империи',
      description: `Бывшая провинция Империи, ныне её прямой вассал: не часть Империи, но подчиняется имперскому совету. Правит младшая ветвь Монстаргов (черновик).`
    })
  }
  S('Великое Герцогство Штирия', {
    secret: 'Великий герцог мечтает стать вампиром.'
  })

  // --- Святая церковь и церковные земли ---
  S('Святая церковь', {
    fullName: 'Святая Церковь Дома Света',
    government: 'Теократия',
    rulerTitle: 'Святой папа',
    religionId: 'lore-house-light',
    heraldry: H('plain', ['#f4f1e8'], 'sun-eye', '#d9a521'),
    description:
      'Отдельное церковное государство на Святом архипелаге, подобие Папской области. Сначала было частью Империи, но ещё при Тейбере I стало независимым, продолжая поддерживать императора. Столица — огромный белый мраморный город с великим храмом в центре, на втором по величине острове архипелага. Все белые земли на карте — архиепархии и архиепископства — вассалы Церкви.'
  })
  for (const st of world.states) {
    const name = st.base.name
    if (/^Архиеп/.test(name)) {
      Object.assign(st.base, {
        overlordId: church?.id ?? '',
        government: 'Церковное княжество, вассал Святой церкви',
        religionId: 'lore-house-light',
        rulerTitle: name.startsWith('Архиепископия') ? 'Архиепископ' : 'Архиепарх',
        heraldry: H('border', ['#f4f1e8', '#d9a521'], 'cross', '#d9a521')
      })
    }
  }

  // --- Церковь Тьмы и юг ---
  S('Церковь Тьмы', {
    fullName: 'Церковь Тьмы',
    government: 'Теократия',
    religionId: 'lore-house-dark',
    heraldry: H('plain', ['#4a2266'], 'chalice', '#0d0b10'),
    description:
      'Малочисленная церковь Дома Тьмы, подобие Папской области. Возводит новый храм Тьмы взамен Великого храма Наллы, от которого остались руины в Пустоши Наллы.'
  })
  S('Пустошь Наллы', {
    government: 'Нет власти (клановые банды)',
    description:
      'Выжженная войной пустыня, где правят лишь бесконечные стычки местных клановых бандитов. Здесь стоял Великий храм Наллы, построенный Джакастой I; ныне — руины из тёмного мрамора. Когда-то эти земли принадлежали Королевству пустынь.'
  })
  S('Джака', {
    culture: 'Нарги, дукулиты',
    religionId: 'lore-house-dark',
    description: 'Наследница Королевства пустынь Джакасты I, разгромленного Тейбером в Великой южной войне.'
  })
  S('Пираты', {
    government: 'Пиратские кланы',
    description: 'Острова, захваченные кланами пиратов.'
  })

  // --- Республики ---
  S('Республика', {
    government: 'Аристократическая республика',
    heraldry: H('plain', ['#1f3f8f'], 'chain', '#f4f1e8'),
    description:
      'Самая мощная республика пост-имперского мира. Парламент избирается народом, но заседают в нём почему-то только аристократы. Власть держится на сильном лидере, избранном парламентом, который старается удержать все столпы власти. Пережила кровопролитную внутреннюю гражданскую войну. Претендует на место Империи на мировой арене, начинает экспансию на пост-имперское пространство и борется с Империей за влияние повсюду. Южные республики — её союзники.'
  })
  for (const name of ['Кальтранская Республика', 'Вуфинская Республика', 'Республика Шеша', 'Тоскана']) {
    S(name, {
      government: 'Торговая республика',
      description:
        'Торговая республика, союзник Республики. Основана генералами, откололись от основной власти ради самоопределения народа, среди которого выросли.' +
        (name === 'Кальтранская Республика' ? ' Народ — кальтранцы: обязательное образование для всех, вольные воители, работорговля.' : '')
    })
  }
  S('Семья Каяя', {
    government: 'Вольный торговый город',
    description: 'Главный вольный торговый город, владение самой богатой семьи бывшей Империи.'
  })

  // --- Север, восток, запад ---
  S('Креит', { culture: 'Нордиды', description: 'Нордиды — «викинги» мира Глеудероффа.' })
  for (const name of ['Земли Севера', 'Высокогорное Княжество', 'Республика Чеафарал', 'Фарвольская лига']) {
    S(name, { description: 'Часть земель, где когда-то стояли Северное королевство нордов и Империя гор дварфов и гномов.' })
  }
  S('Эльфборн', { culture: 'Эльфы', description: 'Джунгли эльфов. Когда-то эльфы жили здесь в изоляции за Стеной отчаяния; север Эльфборна входил в Империю.' })
  S('Олекохт', { culture: 'Элуины', religionId: 'lore-house-light', description: 'Страна элуинов — светлых ладэсов, бежавших от гонений в Кайриме.' })
  S('Крайдонианская Лига', { culture: 'Элеоны', description: 'Единственное государство элеонов — 500 великих семей, потомков команды адмирала фон Рокруа и местных эльфов.' })
  S('Королевство Болетария', { description: 'Здесь верховным богом почитается Дагот.' })
  S('Орда', { culture: 'Орки' })
  S('Углук', { culture: 'Огры и тролли', description: 'Государство огров и троллей в центре Златайских земель; постоянно враждует со златайцами. Боги Углука — пятеро, верховный — Гурб-Гаш, пятый — Бурдяк.' })
  S('Алые Королевства', { description: 'Бывшая часть Империи.' })
  S('Кростфорд', { description: 'Бывшая часть Империи.' })
  S('Офир', { description: 'Бывшая часть Империи.' })
  S('Объединённые Берега Гренинсворда', { description: 'Берега залива Гренинсворд; народы залива почитают Иссикара, хранителя вод.' })
}
