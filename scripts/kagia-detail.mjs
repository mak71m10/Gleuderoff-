// Империя Кагия на карте: Целведель — столица у Семи ворот, Штайнеррит — город каменоломен, Верельвейлер — замок Кагиев;
// пустошь с колодцами и караванной дорогой, лесные деревни Унтерландии; описания всех поселений, места, походы гвардии.
// Запуск после harnmark-detail.mjs: node scripts/kagia-detail.mjs
import { readFileSync, writeFileSync } from 'fs'
import { STATE } from './lore/kagia.mjs'

const WORLD = 'resources/default-world/world.json'
const world = JSON.parse(readFileSync(WORLD, 'utf8'))
const YEAR = world.calendar.months.reduce((s, m) => s + m.days, 0)
const D = (y) => Math.round((y - 1) * YEAR)
let seed = 20261121
const rnd = () => ((seed = (Math.imul(seed, 1664525) + 1013904223) >>> 0) / 4294967296)
const pick = (a) => a[Math.floor(rnd() * a.length)]
const st = world.states.find((s) => s.base.name === STATE)
const admin = new Map(world.adminRegions.map((a) => [a.id, a]))

const provs = world.provinces.filter((p) => p.owners?.at(-1)?.[1] === st.id)
const byName = (nm) => provs.find((p) => p.name === nm)
const cel = byName('Целведель')
if (cel) cel.settlement = { ...(cel.settlement ?? { x: cel.x, y: cel.y }), type: 'city' }

const sx = (p) => p.settlement ?? p
const landOf = (p) => admin.get(p.areaId)?.name ?? ''
const FIRST = ['Ганс', 'Вильгельм', 'Ульрих', 'Эберхард', 'Лотар', 'Георг', 'Бертольд', 'Рупрехт', 'Мартина', 'Гертруда', 'Кунигунда', 'Матиас']
const LAST = ['Шмид', 'Брунн', 'Фельдер', 'Майер', 'Кольб', 'Ланг', 'Хубер', 'Вагнер', 'Зандер', 'Пфайль']
const person = () => `${pick(FIRST)} ${pick(LAST)}`

const NOTE = [
  'Над въездом стоит арка не по росту деревни — «малые ворота торга»: на ней фогт раз в год мелом пишет цену нынешнего императора.',
  'Дети играют в «торги»: ставят камешки за деревянный венец, а у кого камешки кончились, тот кричит «ворота открыты!» и бежит вокруг колодца.',
  'В последний день Драгоса трактир полон: спорят на гроши, внесёт ли император взнос, и ставки пишут углём на балке.',
  'На стене в доме старосты висят пять лубков с императорами — у каждого под портретом цена в марках, как у товара.',
  'Каждый двор платит «копейный грош» — по грошу за каждые сто копий гвардии; в деревне знают, сколько их сейчас, лучше, чем сколько коров.',
  'На краю деревни живёт отставной гвардеец на свою долю взносов; его багряный плащ сушится на заборе, и дети обходят двор стороной.',
  'У колодца лежит старый межевой камень с серебряным дубом Лауэнштайна; камень моют к Ячори, хотя никто уже не помнит зачем.',
  'Постоялый двор держит семь коновязей — по одной на каждую дорогу Семи ворот, и погонщики привязывают мулов к «своей».'
]
const FOREST = ['дёготь и смолу', 'уголь для кузниц Целведеля', 'строевой бук', 'мёд и воск', 'грибы и лыко']
const STEPPE = ['овец и мулов для караванов', 'воду для караванов из глубоких колодцев', 'ячмень на поливных клиньях', 'солёный сыр', 'кожи и сбрую']

let n = 0
for (const p of provs.filter((x) => x.settlement)) {
  const t = p.settlement.type
  const lines = []
  if (p.name === 'Целведель') {
    lines.push('Целведель — столица Кагии у Семи ворот: таможня с семью арками на перекрёстке семи имперских дорог, вокруг которой вырос город погонщиков, менял и гвардейцев. Посреди площади стоит медная доска Глашатая, вогнутая от шести ударов молотка.')
    lines.push('Здесь Ценовая палата Векслеров, контора Дома Каяя через улицу от неё, казармы Багряной гвардии и Капелла Ворот, где на стене висят свинцовые бирки с ценой каждого императора. Император Отмар Штайн живёт в бывшем доме таможенного префекта и в день взноса сам выходит смотреть, как считают монеты.')
  } else if (p.name === 'Штайнеррит') {
    lines.push('Штайнеррит — город каменоломен у подножия гор Фейноко: серые карьеры ступенями над крышами, телеги с блоками на всех дорогах. Гнездо Дома Штайнов и нынешнего императора.')
    lines.push('В 1009 г. Отмар поставил здесь Ворота Торга выше городской стены — из своего камня. Горцы Фейноко спускаются сюда менять сушёную рыбу и шерсть на соль и железо.')
  } else if (p.name === 'Верельвейлер') {
    lines.push('Верельвейлер — замок Кагиев на скалистом холме над Таварвайтской границей: имперская кладка, круглые башни и огромные ворота с орлом пошлинной стражи. Здесь живёт бывший император Гай Кагий и каждый Драгос посылает слугу узнать, внёс ли Отмар взнос.')
    lines.push('В городке под замком — меняльные лавки Векслеров и дом купца Дитмара Ланга. В замковом погребе по вечерам собираются «Сыновья Легата».')
  } else if (t === 'castle') {
    lines.push(`${p.name} — замок фогта с воротами шире, чем нужно замку. Комендант — ${person()}.`)
    lines.push(pick(NOTE))
  } else if (t === 'town') {
    lines.push(`${p.name} — городок на караванной дороге: рынок, меняльная лавка и Ворота Торга на площади. Фогт — ${person()}.`)
    lines.push(pick(NOTE))
  } else if (p.terrain === 6) {
    lines.push(`${p.name} — деревня пустоши: глинобитные дома под терракотой, глубокий колодец с воротом и загоны для мулов. Держат ${pick(STEPPE)}; колодец принадлежит Ротбрукам.`)
    lines.push(`Староста — ${person()}.`)
    lines.push(pick(NOTE))
  } else if (p.terrain === 2) {
    lines.push(`${p.name} — лесная деревня Унтерландии: фахверковые дома в буковом лесу, смолокурня на опушке. Возят в Целведель ${pick(FOREST)}.`)
    lines.push(`Староста — ${person()}.`)
    lines.push(pick(NOTE))
  } else {
    lines.push(`${p.name} — деревня на краю пустоши: поля ячменя, мельница и арка у въезда. Староста — ${person()}.`)
    lines.push(pick(NOTE))
  }
  lines.push(`${landOf(p)}; живут имперцы.`)
  p.description = lines.join(' ')
  n++
}

const place = (id, name, type, at, from, description, stateId = '', off = [14, 10], ruler = '') => {
  const old = world.places.find((p) => p.id === id)
  world.places = world.places.filter((p) => p.id !== id)
  world.places.push({ id, mapId: 'world', x: Math.round(at.x) + off[0], y: Math.round(at.y) + off[1], ...(old?.innerMapId ? { innerMapId: old.innerMapId } : {}), base: { name, type, stateId, population: '', ruler, image: '', description }, history: [], from: from == null ? null : D(from), to: null })
}
const stein = byName('Штайнеррит'), verel = byName('Верельвейлер'), verer = byName('Верерхаузен'), morer = byName('Морербрук'), rot = byName('Ротбрук'), erv = byName('Эрведель')
place('lore-kj-capital', 'Целведель', 'capital', sx(cel), null, '**Столица Империи Кагия.** Семь ворот, площадь торгов, Ценовая палата, казармы Багряной гвардии, Капелла Ворот.', st.id, [0, 0], 'Император Отмар Штайн')
place('lore-kj-gates', 'Семь ворот', 'landmark', sx(cel), 312.2, '**Площадь торгов.** Имперская таможня с семью арками; здесь продают трон и считают взносы.', '', [-16, -12])
place('lore-kj-pricehall', 'Ценовая палата', 'landmark', sx(cel), 978.5, '**Залоги и Ценовая книга.** Меняльная контора Векслеров; через улицу — контора Каяя.', '', [16, -12])
if (stein) place('lore-kj-quarry', 'Каменоломни Штайнеррита', 'landmark', sx(stein), 1009.6, '**Камень императора.** Карьеры Дома Штайнов; в залоге у Каяя.', '', [-14, 12])
if (verel) place('lore-kj-verel', 'Погреб Верельвейлера', 'landmark', sx(verel), 1008, '**Замок Кагиев.** Здесь живёт Гай Кагий и собираются «Сыновья Легата».', '', [14, -10])
if (rot) place('lore-kj-wells', 'Колодцы Ротбруков', 'landmark', sx(rot), 991.8, '**Вода пустоши.** В Сухой год Ротбруки закрыли два колодца, и Брассер потерял трон.', '', [12, 12])
if (verer) place('lore-kj-1002', 'Стычки у Верерхаузена', 'battle', sx(verer), 1002.5, '**1002.** Харнмаркские фуражиры; Вольфрам Ротбрук и Гизела Хальм три недели держат границу.', '', [10, -10])
if (morer) place('lore-kj-978', 'Изгнание комиссаров', 'battle', sx(morer), 978.2, '**978.** Пошлинная стража выгоняет комиссаров Республики из Унтерландии за сорок дней.', '', [10, 10])

world.armies = (world.armies ?? []).filter((a) => !a.id.startsWith('lore-army-kj-'))
const pt = (p, y) => { const s = sx(p); return { x: Math.round(s.x), y: Math.round(s.y), date: D(y) } }
if (cel && erv && morer) world.armies.push({ id: 'lore-army-kj-978', name: 'Пошлинная стража Марцелла Кагия (978)', mapId: 'world', stateId: st.id, color: '#b8323a', waypoints: [pt(cel, 978.1), pt(erv, 978.15), pt(morer, 978.2), pt(cel, 978.3)] })
if (cel && verer) world.armies.push({ id: 'lore-army-kj-1002', name: 'Багряная гвардия у Верерхаузена (1002)', mapId: 'world', stateId: st.id, color: '#b8323a', waypoints: [pt(cel, 1002.4), pt(verer, 1002.5), pt(cel, 1002.6)] })

writeFileSync(WORLD, JSON.stringify(world, null, 1))
const cnt = {}
for (const p of provs) if (p.settlement) cnt[p.settlement.type] = (cnt[p.settlement.type] ?? 0) + 1
console.log(`Кагия: описаний ${n}, по типам ${JSON.stringify(cnt)}`)
