// Княжества Гарефорда на карте: десять княжеств-округов по кругу Светоча, столица там, где фонарь (Орхайм, 1010 г.).
// Крупные центры — Зигштейн, Корерберг, Кирхберг, Ландштадт (города) и порт Орхайм; княжеские центры — городки; остальное — горные и лесные деревни.
// Описания всех поселений, места (Собор Пламени, Цепная канцелярия, Пфандхаус, поля сражений), походы Кольцевого войска.
// Запуск после crydon-detail.mjs: node scripts/gareford-detail.mjs
import { readFileSync, writeFileSync } from 'fs'
import { GF_NAMES, STATE } from './lore/gareford.mjs'

const WORLD = 'resources/default-world/world.json'
const world = JSON.parse(readFileSync(WORLD, 'utf8'))
const YEAR = world.calendar.months.reduce((s, m) => s + m.days, 0)
const D = (y) => Math.round((y - 1) * YEAR)
let seed = 20261109
const rnd = () => ((seed = (Math.imul(seed, 1664525) + 1013904223) >>> 0) / 4294967296)
const pick = (a) => a[Math.floor(rnd() * a.length)]
const chance = (p) => rnd() < p
const st = world.states.find((s) => s.base.name === STATE)
const admin = new Map(world.adminRegions.map((a) => [a.id, a]))
const mine = (p) => p.owners?.at(-1)?.[1] === st.id
const provs = world.provinces.filter(mine)
const byName = (nm) => provs.find((p) => p.name === nm)
const sx = (p) => p.settlement ?? p
const landOf = (p) => admin.get(p.areaId)?.name ?? ''
const person = (women) => `${pick(women ? GF_NAMES.women : GF_NAMES.men)} ${pick(GF_NAMES.families)}`

// ---------- типы поселений ----------
const TYPE = { Кирхберг: 'city', Ландштадт: 'city', Зигштейн: 'city', Корерберг: 'city', Орхайм: 'port' }
for (const [nm, t] of Object.entries(TYPE)) { const p = byName(nm); if (p) p.settlement = { ...(p.settlement ?? { x: p.x, y: p.y }), type: t } }

// какому дому принадлежит округ
const DOMAIN = {
  'Округ Эберенведель': ['Эберенведель', 'Дом Эберенведель'], 'Округ Кирхберг': ['Кирхберг', 'Князь-епископство Кирхберг'], 'Округ Фрейберг': ['Фрейберг', 'Дом Фрейберг'],
  'Округ Корерберг': ['Корерберг', 'Дом Корер'], 'Округ Ландштадт': ['Ландштадт', 'Дом Ландштадт'], 'Округ Орхайм': ['Орхайм', 'Дом Хельмбрехт'], 'Округ Ротберг': ['Ротберг', 'Дом Эберенведель'],
  'Округ Зигштейн': ['Зигштейн', 'Дом Зигштейн'], 'Округ Фрейрит': ['Фрейрит', 'Дом Ройгард'], 'Округ Ройгард': ['Ройгард', 'Дом Ройгард']
}

const FARM = ['ячмень и рожь на узких террасах', 'овец и козий сыр', 'пасеки и яблони', 'коров и масло', 'лён и коноплю']
const TIMBER = ['рубят лес для плотов', 'гонят дёготь и смолу', 'жгут уголь для плавилен', 'делают клёпку и бочки', 'вяжут плоты для сплава']
const MINE = ['серебряные штольни', 'железную руду', 'свинец', 'каменоломню', 'медные ямы']
const LAKE = ['форель и хариуса', 'озёрных щук', 'сигов и налимов', 'горных раков']
const NOTE = [
  'У околицы стоит маленькая часовня Пламени: над дверью — медный фонарик, который зажигают от лампады Кирхберга в Ночь Передачи.',
  'Когда Светоч проходит по этим землям, дорогу чистят и вешают на столбах свечи; деревня три дня не работает.',
  'Здесь помнят набег Креита 988 года: на сельской площади до сих пор стоит обгорелый столб, который никто не решается убрать.',
  'Староста держит копию Хартии Светоча на лавке у печи и читает её вслух на сходе.',
  'Дети здесь играют в «Круг»: бросают жребий, кто будет носить фонарь, и по очереди отдают его друг другу.',
  'Деревенские считают очереди князей, как погоду: кто когда держал Светоч и как после этого жилось.',
  'Над крышами по вечерам вьётся дымок: топят по-горному, в избах с высокими печами и низкими дверьми.',
  'Рядом проходит старая имперская дорога, брошенная после 976 года; её камни растащили на стены.'
]

let n = 0
for (const p of provs.filter((x) => x.settlement)) {
  const t = p.settlement.type
  const dom = DOMAIN[landOf(p)] ?? ['', '']
  const lines = []
  if (p.name === 'Орхайм') {
    lines.push('Орхайм — единственный порт Княжеств и столица 1010 г. (столица стоит там, где висит Светоч). Город на заливе: серые каменные причалы, склады из тёмного дуба и три ряда башен вдоль воды, а над всем — Светочная башня с огнём, который видно с моря.')
    lines.push('Здесь Пфандхаус Хельмбрехтов, чьи векселя ходят по всем княжествам, и Дворец Светоча, куда фонарь привезли в Ночь Передачи 1009 г. Правит Светочедержица Ида Хельмбрехт; начальница порта — Бригитта Лаубах.')
  } else if (p.name === 'Кирхберг') {
    lines.push('Кирхберг — церковное княжество и сердце веры Круга. На холме над городом стоит Собор Пламени: в нём горит алтарное Пламя, от которого зажигают Светоч. Рядом — Цепная канцелярия, где записаны Хартия, залоги и отводы.')
    lines.push('Управляет городом князь-аббатиса Хильдегарда; в Ночь Передачи сюда съезжаются все десять князей. Белые стены, золотые шпили и сотни свечей в окнах.')
  } else if (p.name === 'Зигштейн') {
    lines.push('Зигштейн — каменный город-крепость на скале над перевалом, гнездо вождей восстания 976 г. и самый горный из княжеств. Черноорлиные штандарты на каждой башне; у ворот — Светочная башня, поставленная Ульрихом «Пламенником» ещё при первом круге.')
    lines.push('Здесь правит Ульрих II; в казармах живут лучшие копейщики Кольцевого войска, а в одной из башен — заложник Эйвинд, сын хёвдинга Фьялэтта.')
  } else if (p.name === 'Корерберг') {
    lines.push('Корерберг — рудничный город на склонах высокого хребта: штольни выходят прямо на улицы, а над кровлями — дымы плавилен. Красный молот Дома Корер на каждом цеховом знаке.')
    lines.push('Главная шахта затоплена в 1005 г.; добыча упала втрое, и Ханс Корер заложил свою очередь Хельмбрехтам. Над городом стоит Светочная башня, но огонь на ней зажигают редко.')
  } else if (p.name === 'Ландштадт') {
    lines.push('Ландштадт — перевалочный город на сходе трёх горных дорог: сюда стекаются караваны из Фарвола, Гренинсворда и Орхайма. Купеческие дворы с воротами на улицу, рыночная площадь с белой башней Дома Ландштадт.')
    lines.push('Правит Маргарета Ландштадт; кастелян — Фолькер Брасштейн. Город берёт пошлину с каждого воза и держит монополию на соль.')
  } else if (p.name === 'Висхайм') {
    lines.push('Висхайм — сожжённая в 988 г. деревня на перевале: Креит прошёл здесь, а Бертольд Корер не пришёл. Остались чёрные стены и колодец; новые дома строят в стороне, а на пепелище никто не селится.')
  } else if (p.name === 'Эльминфельд') {
    lines.push('Эльминфельд — замок над рудничными долинами Корерберга: массивные стены, казармы Кольцевого войска и склад серебра для Светочедержца. Командует кастелян из Дома Корер.')
  } else if (p.name === 'Ландельвальд') {
    lines.push('Ландельвальд — лесной замок на Килском хребте: деревянные стены на каменном основании, дымовые сигналы на башнях. Заставы Горной стражи высылают отсюда разъезды к Фьялским перевалам.')
  } else if (t === 'town') {
    lines.push(`${p.name} — княжеский городок ${dom[1] ? `земель дома «${dom[1].replace(/^Дом |^Князь-епископство /, '')}»` : ''}: ратуша с башенкой, рынок и дом князя, а над ними — маленькая Светочная башня. Живут ${pick(['сплавом и лесом', 'серебром и торгом', 'перевозом и мастерскими', 'шахтами и овцеводством'])}.`)
    lines.push(`Старший писарь — ${person()}; Цепная канцелярия присылает сюда раз в год проверку записей.`)
    lines.push(pick(NOTE))
  } else if (t === 'castle') {
    lines.push(`${p.name} — горный замок: бастионы на скале, караулка и склад Кольцевого войска. Комендант — ${person()}.`)
  } else if (t === 'fishing') {
    lines.push(`${p.name} — озёрно-речной посёлок: лодки, сети и коптильни; ловят ${pick(LAKE)} и ${pick(LAKE)}. Старшина — ${person()}.`)
    lines.push(pick(NOTE))
  } else if (p.terrain === 5 || p.terrain === 4) {
    lines.push(`${p.name} — высокогорная деревня: ${pick(['каменные дома с плоскими крышами', 'пастушьи хижины и сыроварня', 'штольни и отвалы', 'терраса с овцами'])}. Работают на ${pick(MINE)} и держат ${pick(FARM)}.`)
    lines.push(`Старшина — ${person()}.`)
    lines.push(pick(NOTE))
  } else if (p.terrain === 2 || p.terrain === 6) {
    lines.push(`${p.name} — лесная деревня: ${pick(['дома из тёмного дуба', 'избы с высокими крышами', 'сруб и лесопилка'])}, делянки и запань на реке. ${pick(TIMBER).replace(/^./, (c) => c.toUpperCase())} и ${pick(TIMBER)}.`)
    lines.push(`Староста — ${person()}.`)
    lines.push(pick(NOTE))
  } else {
    lines.push(`${p.name} — деревня в долине: ${pick(['белёные дома с чёрными балками', 'мельница на ручье и пекарня', 'красные черепичные крыши и колодец'])}. Здесь выращивают ${pick(FARM)}.`)
    lines.push(`Староста — ${person(chance(0.3))}.`)
    lines.push(pick(NOTE))
  }
  lines.push(`${landOf(p)}${dom[0] ? `; земли ${dom[1].replace(/^Дом /, 'дома ').replace(/^Князь-епископство/, 'князь-епископства')}` : ''}.`)
  p.description = lines.join(' ')
  n++
}

// ---------- места ----------
const place = (id, name, type, at, from, description, stateId = '', off = [14, 10], ruler = '') => {
  const old = world.places.find((p) => p.id === id)
  world.places = world.places.filter((p) => p.id !== id)
  world.places.push({ id, mapId: 'world', x: Math.round(at.x) + off[0], y: Math.round(at.y) + off[1], ...(old?.innerMapId ? { innerMapId: old.innerMapId } : {}), base: { name, type, stateId, population: '', ruler, image: '', description }, history: [], from: from == null ? null : D(from), to: null })
}
const cap = byName('Орхайм'), kirch = byName('Кирхберг'), korer = byName('Корерберг'), zig = byName('Зигштейн'), freib = byName('Фрейберг'), roi = byName('Ройгард'), freir = byName('Фрейрит'), vis = byName('Висхайм'), land = byName('Ландштадт')
place('lore-gf-capital', 'Орхайм', 'capital', sx(cap), null, '**Столица (1010 г.).** Светоч висит здесь, и страна правится отсюда. Порт, Пфандхаус Хельмбрехтов и Дворец Светоча.', st.id, [0, 0], 'Светочедержица Ида Хельмбрехт')
place('lore-gf-cathedral', 'Собор Пламени', 'temple', sx(kirch), 976.4, '**Святыня Круга.** Белый собор на холме над Кирхбергом: здесь горит алтарное Пламя, от которого зажигают Светоч, и проходит Ночь Передачи.', '', [-16, -12])
place('lore-gf-chain', 'Цепная канцелярия', 'landmark', sx(kirch), 977.1, '**Архив Круга.** Хартия Светоча, Цепная книга залогов, свечи отвода. Канцлер — Ортвин Кельгард.', '', [16, -12])
place('lore-gf-pfand', 'Пфандхаус Хельмбрехт', 'landmark', sx(cap), 983.2, '**Банк Орхайма.** Склад векселей на набережной: здесь принимают в залог очередь на Светоч.', '', [-16, 12])
place('lore-gf-lantern-tower', 'Светочная башня Зигштейна', 'landmark', sx(zig), 977.1, '**Башня Ульриха Пламенника.** Каменный ствол с галереей и фонарной клетью; огонь зажигают в Ночь Передачи.', '', [16, 12])
place('lore-gf-silver', 'Серебряная жила Фрейберга', 'landmark', sx(freib), 990.3, '**Найдена в 990 г.** Основа монеты Круга; к 1010 г. иссякает.', '', [-14, 14])
place('lore-gf-flood', 'Затопленная шахта Корерберга', 'landmark', sx(korer), 1005, '**1005 г.** Главную шахту залило водой из подземного озера; добыча упала втрое, Дом Корер в долгах.', '', [-14, 12])
if (vis) place('lore-gf-visheim', 'Сожжённый Висхайм', 'battle', sx(vis), 988.6, '**988.6.** Креит сжёг перевальную деревню, Фрейрит и Ройгард; Бертольд Корер не пришёл на помощь.', '', [12, -12])
if (roi) place('lore-gf-pass', 'Перевал Лиутпольда', 'battle', sx(roi), 994.3, '**994.3.** Лиутпольд Ройгард погиб здесь, штурмуя Фьялские борги; остаток срока Светоч держал маршал Рупрехт Альтинберг.', '', [18, -14])
if (land) place('lore-gf-landgate', 'Гарефордские ворота', 'landmark', sx(land), 980.3, '**Ворота в горы** со стороны Фарвола: через них входят лес, рыба и кожи; пошлину берёт Ландштадт.', '', [-18, -10])

// ---------- походы ----------
world.armies = (world.armies ?? []).filter((a) => !a.id.startsWith('lore-army-gf-'))
const pt = (p, y) => { const s = sx(p); return { x: Math.round(s.x), y: Math.round(s.y), date: D(y) } }
if (cap && korer) world.armies.push({ id: 'lore-army-gf-988', name: 'Кольцевое войско у Корерберга (988)', mapId: 'world', stateId: st.id, color: '#8a96a8', waypoints: [pt(cap, 988.4), pt(korer, 988.6), pt(korer, 988.8)] })
if (cap && roi) world.armies.push({ id: 'lore-army-gf-994', name: 'Поход Лиутпольда на Фьялские борги (994)', mapId: 'world', stateId: st.id, color: '#6a8a74', waypoints: [pt(cap, 994.1), pt(freir ?? roi, 994.2), pt(roi, 994.3)] })

writeFileSync(WORLD, JSON.stringify(world, null, 1))
const cnt = {}
for (const p of provs) if (p.settlement) cnt[p.settlement.type] = (cnt[p.settlement.type] ?? 0) + 1
console.log(`Княжества Гарефорда: описаний ${n}, по типам ${JSON.stringify(cnt)}`)
