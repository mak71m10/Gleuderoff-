// Высокогорное Княжество на карте: города на вершинах (Химмельскранц, Вайсхорн, Шнеевахт) вместо дварфских городков,
// описания всех поселений (Венец, замки Горной стражи и великих домов, рудничные деревни подгорников, гномьи долины),
// места (Ступени, Великий Ворот, Колокол жалобы, Белая стена, Стояние под Кранцем), поход III легиона в 977 г.
// Придумано по поручению автора (07.11.2026) — «черновик». Детерминированно.
// Запуск после farvol-detail.mjs: node scripts/highland-detail.mjs
import { readFileSync, writeFileSync } from 'fs'
import { HL_CITIES, HL_NAMES, STATE, hlRace } from './lore/highland.mjs'

const WORLD = 'resources/default-world/world.json'
const world = JSON.parse(readFileSync(WORLD, 'utf8'))
const YEAR = world.calendar.months.reduce((s, m) => s + m.days, 0)
const D = (y) => Math.round((y - 1) * YEAR)
let seed = 20261108
const rnd = () => ((seed = (Math.imul(seed, 1664525) + 1013904223) >>> 0) / 4294967296)
const pick = (a) => a[Math.floor(rnd() * a.length)]
const chance = (p) => rnd() < p
const st = world.states.find((s) => s.base.name === STATE)
const admin = new Map(world.adminRegions.map((a) => [a.id, a]))

// города на вершинах стоят на месте прежних дварфских городков; удел, названный по городку, получает новое имя
for (const c of HL_CITIES) {
  const p = world.provinces.find((x) => x.id === c.id)
  const area = admin.get(p.areaId)
  if (area?.name === `Чертог ${c.old}`) area.name = `Удел ${c.name}`
  p.name = c.name
  p.settlement.type = c.type
}

const provs = world.provinces.filter((p) => p.owners?.at(-1)?.[1] === st.id)
const landOf = (p) => admin.get(admin.get(p.areaId)?.parentId)?.name ?? ''
const dist = (a, b) => Math.hypot(a.x - b.x, a.y - b.y)
const sx = (p) => p.settlement ?? p
const byName = (nm) => provs.find((p) => p.name === nm)
const race = new Map(provs.filter((p) => p.settlement).map((p) => [p, hlRace(p.name, p.settlement.type, p.terrain)]))
const knight = () => `${pick(HL_NAMES.men)} фон ${pick(HL_NAMES.knights)}`
const dwarf = () => pick(HL_NAMES.dwarfs)
const gnome = () => pick(HL_NAMES.gnomes)

// чьи замки: кому какой рудник, перевал или карьер
const HOLD = {
  'Морддум': ['silber', 'Серебряный замок над жилой Морддума: здесь Зильберталии взвешивают серебро, прежде чем оно уйдёт в Рудный Ворот.'],
  'Гархольд': ['gams', 'Замок над Гарскими копями, самым большим рудником Княжества. Под стенами — штольни, отвалы и долговые штольни, откуда никто не поднимается.'],
  'Тор-Гард': ['gams', 'Замок Гамсвальдов над медными штольнями копей; отсюда надсмотрщики спускаются в забой.'],
  'Азг-Агрим': ['felsen', 'Замок Фельзенау над Белой стеной — карьерами белого мрамора. От замка вниз идёт Белый Ворот, по которому поднимают глыбы.'],
  'Тор-Азум': ['talmar', 'Бывший замок Тальмаров. После Спуска 1004 г. князь отдал его Горной страже; гербы Тальмаров сбиты со стен.'],
  'Барак-Гард': ['ritter', 'Застава Горной стражи на перевалах Дум-Аского хребта, к Фарвольской лиге. Над дорогой — сложенный камнепад.'],
  'Килхольд': ['ritter', 'Пограничный замок Горной стражи против Земель Севера.'],
  'Морддор': ['ritter', 'Замок у подножия Ступеней — единственной пешей дороги на Венец. Здесь стояли Горные волки в 977 г.']
}
const HOUSE = { silber: 'Дома Зильберталь', gams: 'Дома Гамсвальд', felsen: 'Дома Фельзенау', talmar: 'Дома Тальмар', ritter: 'Дома Риттерау', schnee: 'Дома Шнееберг' }
const ORE = ['серебро', 'медь', 'железо', 'свинец', 'олово', 'горный хрусталь']
const DWARF_NOTE = [
  'На краю деревни — отвал пустой породы выше крыш; дети играют на нём, пока не позовут в забой.',
  'Отсюда видно Венец: ночью на вершине горит огонь Храма, и подгорники говорят, что это единственный свет, который им оттуда достаётся.',
  'Рудная подать — две бадьи из трёх. Третью меняют на хлеб, который поднимают на Венец и продают обратно вниз.',
  'Здесь помнят Обман Зигмунда: старики плюют, когда слышат слово «грамота».',
  'В горне Магнуса у старосты красное стекло — знак, что из деревни кто-то ушёл в лигу.',
  'Надсмотрщик с Террас приезжает раз в неделю, считает бадьи и уезжает до темноты.'
]
const GNOME_NOTE = [
  'Половина мужчин — на станциях Ворота: неделю крутят колёса наверху, неделю дома.',
  'На ручье — колесо, которое крутит мельницу и маленький подъёмник на верхние террасы.',
  'Дома высокие и узкие, с медными флюгерами: гномы строят так, будто хотят хоть чем-то дотянуться до Венца.',
  'Здесь вспоминают Стоячий ворот (998) как праздник и пьют за Квирина Шпуле.',
  'Сыр и пиво отсюда поднимают на Венец; гномам за них платят медью, людям продают за серебро.'
]
const FIELDS = ['ячмень', 'овёс', 'горную репу', 'коз и сыр', 'хмель', 'лён']

let n = 0
const capital = byName('Химмельскранц')
for (const [p, r] of race) {
  const t = p.settlement.type
  const land = landOf(p)
  const lines = []
  const hold = HOLD[p.name]
  if (p === capital) {
    lines.push('Химмельскранц — столица Княжества, город на Венце: каменная платформа обхватывает вершину Химмельсхорна на высоте тысячи трёхсот саженей, и на ней стоит весь город. Над ним, на самой вершине, — дворец Адлерхорнов, выше Храма на Вершине.')
    lines.push('Вокруг вершины кольцами — уделы Венца, ниже по склонам — Карниз и Террасы. Попасть сюда можно только Великим Воротом или по Ступеням: две тысячи ступеней в скале и семь ворот.')
    lines.push('Здесь живёт князь Максимилиан Адлерхорн, заседает Совет Венца в Солнечной галерее и звонит Вечерний колокол. Внизу, под облаками, — Подошва.')
  } else if (p.name === 'Вайсхорн') {
    lines.push('Вайсхорн — второй город на вершине: платформа из белого мрамора Фельзенау вокруг пика, который видно из Штирии. Здесь живут рыцари Горной стражи и купцы Террас; в 1009 г. сюда подняли Белый Ворот.')
    lines.push('В Вайсхорне держат заложников, взятых у подгорников в 1002 г.: их так и не отпустили.')
  } else if (p.name === 'Шнеевахт') {
    lines.push('Шнеевахт — замок-город Шнеебергов на заснеженной вершине у восточной границы. Отсюда Ключники видят все дороги к Фарвольской лиге; здесь хранят запасные канаты и ключи Ворота.')
  } else if (hold) {
    lines.push(`${p.name} — ${hold[1]}`)
    lines.push(`Замком правит ${knight()}, вассал ${HOUSE[hold[0]]}.`)
  } else if (r === 'alpine') {
    lines.push(`${p.name} — замок Горной стражи на скале над долиной: каменная башня с крутой деревянной крышей, двор, конюшни и камнепад над дорогой. Держит его ${knight()}.`)
    lines.push(land === 'Гарские копи' ? 'Замок стережёт рудники подгорников и дорогу к станции Ворота.' : 'Замок стережёт перевалы и пастбища.')
  } else if (p.name === 'Ул-Зум') {
    lines.push('Ул-Зум — главный город Подошвы, у дороги к нижней станции Великого Ворота. Дварфы, гномы и одна человеческая семья: здесь живёт опущенный дом Тальмар. На станции висит Колокол жалобы.')
    lines.push(`Город держит бургграф с Террас ${knight()}, а улицы — Цех Забоя.`)
  } else if (p.name === 'Грунзум') {
    lines.push('Грунзум — город гномов Братства Ворота: мастерские, кузни для канатов и колёс, склады осей и бадей. Здесь живёт старшина Квирин Шпуле.')
  } else if (p.name === 'Грун-Зум') {
    lines.push('Грун-Зум — горн Нижнего света: главный храм Магнуса у подгорников. Жрецы Храма на Вершине терпят его, пока здесь молятся за Венец.')
  } else if (r === 'gnome') {
    lines.push(`${p.name} — гномья деревня в долине: высокие узкие дома, медные флюгера, террасы с полями. Здесь живут гномы-пахари и семьи подъёмщиков.`)
    lines.push(`Растят ${pick(FIELDS)} и ${pick(FIELDS)}; староста — ${gnome()}.`)
    lines.push(pick(GNOME_NOTE))
  } else {
    lines.push(`${p.name} — рудничная деревня подгорников: низкие каменные дома у входа в штольню, отвалы, рудомойни. Здесь живут дварфы.`)
    lines.push(`Добывают ${pick(ORE)}; старший рудокоп — ${dwarf()}${chance(0.35) ? ', чей отец бил в Колокол жалобы и не вернулся' : ''}.`)
    lines.push(pick(DWARF_NOTE))
  }
  const tag = r === 'kranz' ? 'город на вершине, Венец' : r === 'alpine' ? 'люди Горной стражи' : r === 'gnome' ? 'гномы Подошвы' : 'дварфы Подошвы'
  lines.push(`${land}; ${tag}.`)
  p.description = `${lines.join(' ')}\n\n_черновик_`
  n++
}

// ---------- места ----------
const place = (id, name, type, at, from, description, stateId = '', off = [14, 10]) => {
  const old = world.places.find((p) => p.id === id)
  world.places = world.places.filter((p) => p.id !== id)
  world.places.push({ id, mapId: 'world', x: Math.round(at.x) + off[0], y: Math.round(at.y) + off[1], ...(old?.innerMapId ? { innerMapId: old.innerMapId } : {}), base: { name, type, stateId, population: '', ruler: type === 'capital' ? 'Князь Максимилиан Адлерхорн' : '', image: '', description: `${description}\n\n_черновик_` }, history: [], from: from == null ? null : D(from), to: null })
}
place('lore-hl-capital', 'Химмельскранц', 'capital', sx(capital), null, '**Столица на Венце.** Город на каменной платформе вокруг вершины Химмельсхорна; над ним — дворец Адлерхорнов. Дорога — только Ворот и Ступени.', st.id, [0, 0])
place('lore-hl-winch', 'Великий Ворот', 'landmark', sx(capital), null, '**Подъёмники Венца.** Четыре колеса, канаты дварфской стали, гномы Братства Ворота. Ключи — у Шнеебергов.', '', [16, 12])
place('lore-hl-steps', 'Ступени', 'landmark', sx(capital), null, '**Единственная пешая дорога на Венец.** Две тысячи ступеней в скале, семь ворот, камнепады над каждым поворотом.', '', [-16, 12])
place('lore-hl-stand', 'Стояние под Кранцем', 'battle', sx(capital), 977.3, '**977 г.** III Штайнгардский легион сорок дней стоит под Химмельскранцем. Канаты обрезаны, Ступени завалены; после одного штурма легат Эберт уводит легион.', '', [-14, -12])
const ulzum = byName('Ул-Зум')
if (ulzum) place('lore-hl-bell', 'Колокол жалобы', 'landmark', sx(ulzum), null, '**Единственное право подгорников.** Раз в год у нижней станции можно ударить в колокол — и с Венца спустится судья. В 1008 г. ударила Хильда Медная Коса.', '', [14, -10])
const white = byName('Азг-Агрим')
if (white) place('lore-hl-white', 'Белая стена', 'landmark', sx(white), 1006, '**Карьеры белого мрамора Фельзенау.** Отсюда мрамор для дворцов Венца, Штирии и Хауссера; Белый Ворот поднимает глыбы.', '', [14, -10])
const gar = byName('Гархольд')
if (gar) place('lore-hl-mines', 'Гарские копи', 'landmark', sx(gar), null, '**Самый большой рудник Княжества.** Железо и медь Гамсвальдов; долговые штольни.', '', [-14, -10])

// ---------- поход Горных волков ----------
world.armies = (world.armies ?? []).filter((a) => !a.id.startsWith('lore-army-hl-'))
const pt = (p, y) => { const s = sx(p); return { x: Math.round(s.x), y: Math.round(s.y), date: D(y) } }
const southmost = provs.filter((p) => p.settlement).reduce((a, b) => (a.y > b.y ? a : b))
const empireState = world.states.find((s) => s.base.name === 'Империя')
const mord = byName('Морддор')
if (capital && mord) world.armies.push({ id: 'lore-army-hl-977', name: 'III Штайнгардский легион под Кранцем (977)', mapId: 'world', stateId: empireState?.id ?? '', color: '#6a6a5a', waypoints: [pt(southmost, 977.2), pt(ulzum ?? southmost, 977.28), pt(mord, 977.32), pt(capital, 977.36), pt(mord, 977.45), pt(southmost, 977.58)] })

writeFileSync(WORLD, JSON.stringify(world, null, 1))
const cnt = {}
for (const r of race.values()) cnt[r] = (cnt[r] ?? 0) + 1
console.log(`Высокогорное Княжество: описаний ${n}, по облику ${JSON.stringify(cnt)}`)
