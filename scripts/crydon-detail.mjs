// Крайдонианская Лига на карте: все города — на берегу, внутри страны только рудничные посёлки (канон автора 08.11.2026).
// Столица Рокхавен переезжает на берег (меняется местами с Краиланте), внутренние города, замки и храмы становятся посёлками,
// береговые рыбацкие посёлки растут в порты и города; описания всех поселений, места, походы эскадр.
// Запуск после cheafaral-detail.mjs: node scripts/crydon-detail.mjs
import { readFileSync, writeFileSync } from 'fs'
import { CR_NAMES, STATE } from './lore/crydon.mjs'

const WORLD = 'resources/default-world/world.json'
const world = JSON.parse(readFileSync(WORLD, 'utf8'))
const YEAR = world.calendar.months.reduce((s, m) => s + m.days, 0)
const D = (y) => Math.round((y - 1) * YEAR)
let seed = 20261108
const rnd = () => ((seed = (Math.imul(seed, 1664525) + 1013904223) >>> 0) / 4294967296)
const pick = (a) => a[Math.floor(rnd() * a.length)]
const chance = (p) => rnd() < p
const st = world.states.find((s) => s.base.name === STATE)
const admin = new Map(world.adminRegions.map((a) => [a.id, a]))
const byId = (id) => world.provinces.find((p) => p.id === id)
const mine = (p) => p.owners?.at(-1)?.[1] === st.id

// ---------- переезд столицы на берег: Рокхавен ↔ Краиланте ----------
{
  const inland = byId(1144), coast = byId(1197)
  if (inland && coast && inland.name === 'Рокхавен') {
    inland.name = 'Краиланте'
    coast.name = 'Рокхавен'
    inland.settlement.type = 'village'
    coast.settlement = { ...(coast.settlement ?? {}), type: 'city' }
  }
}

// ---------- берег: кто город, кто порт, кто форт ----------
const CITY = ['Тильхавен', 'Доненхавен', 'Ванеэль']
const PORT = ['Тильдейк', 'Зеланте', 'Рокре', 'Донхавен', 'Линехавен', 'Тильенхавен', 'Эльмунд', 'Хофдейк']
const TOWN = ['Ванруа', 'Рокланте', 'Мередейк', 'Земунд', 'Краенэль', 'Варнедам']
const FORT = ['Меренруа', 'Рокенланте', 'Эльланте']
const SET = (names, type) => { for (const nm of names) { const p = world.provinces.find((x) => x.name === nm && mine(x) && x.coastal); if (p) p.settlement = { ...(p.settlement ?? { x: p.x, y: p.y }), type } } }
SET(CITY, 'city'); SET(PORT, 'port'); SET(TOWN, 'town'); SET(FORT, 'castle')
// внутри страны — только посёлки и рудники
for (const p of world.provinces) if (mine(p) && p.settlement && !p.coastal && p.name !== 'Рокхавен' && ['city', 'town', 'port', 'castle', 'temple'].includes(p.settlement.type)) p.settlement.type = 'village'

const provs = world.provinces.filter(mine)
const sx = (p) => p.settlement ?? p
const byName = (nm) => provs.find((p) => p.name === nm)
const person = () => `${pick(CR_NAMES.men)} ${pick(CR_NAMES.families)}`
const landOf = (p) => admin.get(p.areaId)?.name ?? ''

const ORES = ['железную руду', 'олово', 'медь', 'уголь', 'свинец', 'белую глину для верфей']
const FOREST = ['мачтовый лес', 'смолу и дёготь', 'корабельную сосну', 'пеньку для канатов']
const FISH = ['сельдь', 'треску', 'устриц', 'морских раков', 'угрей', 'солёную рыбу']
const MINE_NOTE = [
  'Шахтёры здесь в основном люди: элеоны считают подземную работу людской, а сами спускаются только надсмотрщиками.',
  'Руду возят вниз к берегу на мулах; в сезон дождей штольни заливает, и выход добычи падает вдвое.',
  'Над входом в штольню висит маячный фонарь Церкви Маяка: шахтёры верят, что свет не пускает обвал.',
  'Староста держит запись добычи в бортовом журнале, как на корабле: смена называется «вахтой», а штрек — «палубой».',
  'По вечерам шахтёры поют морские песни, которых никогда не пели в море: их привезли из порта вместе с хлебом.'
]
const COAST_NOTE = [
  'На набережной сушат сети и паруса; над домами возвышается мачта, на которой по праздникам вывешивают вымпелы семей.',
  'Каждый вечер на молу зажигают маячный огонь: он дежурит от заката до рассвета, и дежурный получает долю от каждого прошедшего судна.',
  'Мальчишки здесь учатся вязать узлы раньше, чем читать, а в двенадцать лет получают первый нож и первую вахту.',
  'Корабельный мастер здесь живёт в самом большом доме: к нему несут клятвы, когда закладывают киль.',
  'В порту стоит колокол, в который бьют при входе каждого корабля: по числу ударов знают, чьё судно.'
]

let n = 0
const capital = byName('Рокхавен')
for (const p of provs.filter((p) => p.settlement)) {
  const t = p.settlement.type
  const lines = []
  if (p === capital) {
    lines.push('Рокхавен — столица Крайдонианской Лиги и главная военно-морская база континента. Город стоит на подковообразной бухте: у воды — Большой док, верфи и канатные дворы, выше — белые дома адмиралов, а на мысу над рейдом — Маячный Собор, огонь которого видно за двадцать миль.')
    lines.push('Здесь Адмиралтейство, Дом Вымпелов с пятью сотнями знамён на стенах и Рокхавенский рейд — место, где корабли встают в колонны, выбирая Верховного адмирала. Часть города стоит прямо в море: на сваях, над водой, с мостками между домами.')
    lines.push('Здесь живёт Верховный адмирал Батист ван Краиланте; на рейде зимует Флагманская эскадра.')
  } else if (p.name === 'Тильхавен') {
    lines.push('Тильхавен — второй по величине порт Лиги и главная торговая гавань: сюда заходят караваны из Темерии, суда с пряностями и паломники в Святой архипелаг. На набережной — Рейдовая страховая палата Дома Доненвирен.')
  } else if (p.name === 'Доненхавен') {
    lines.push('Доненхавен — гнездо Дома ван Доненвирен, торговой и страховой столицы Лиги: по этим причалам идут грузы, застрахованные палатой на сотни тысяч. Охранный сбор в 5 % здесь платят все.')
  } else if (p.name === 'Ванеэль') {
    lines.push('Ванеэль — база Южной эскадры. Над гаванью высится башня сигналов, с которой передают флагами приказы до самого Рокхавена; в доках стоят новые фрегаты.')
  } else if (p.name === 'Тильдейк') {
    lines.push('Тильдейк — база Северной эскадры и родина дома Тильдейк, первой «простой» семьи, получившей вымпел (989). Порт суровый, ветреный: на причалах говорят, что здесь корабли зимуют, а люди — служат.')
  } else if (p.name === 'Зеланте') {
    lines.push('Зеланте — база Конвойной эскадры: отсюда уходят охраняемые караваны на север и юг. Здесь же Рейдовая страховая палата ведёт книгу выкупов и пропавших судов.')
  } else if (p.name === 'Меренруа') {
    lines.push('Меренруа — береговая цитадель и гнездо Дома ван Мерен: адмиралов Империи, воевавших в Лесной войне. База Береговой и брандерной эскадры; на скале над бухтой — склады брандеров и бастионы.')
  } else if (t === 'city' || t === 'port') {
    lines.push(`${p.name} — ${t === 'city' ? 'крупный портовый город' : 'порт'} Лиги: верфь, канатный двор, лоцманский дом и причалы, где швартуются ${pick(['эскадренные фрегаты', 'вооружённые торговцы', 'конвойные корабли', 'шхуны Рейдовой палаты'])}.`)
    lines.push(`Порт держит ${person()}, капитан порта; в гавани стоит ${pick(['два', 'три', 'четыре'])} вымпела.`)
    lines.push(pick(COAST_NOTE))
  } else if (t === 'town') {
    lines.push(`${p.name} — береговой городок: ${pick(['рыбный рынок и солеварни', 'верфь малых судов', 'склады соли и бочек', 'канатный двор и лоцманская школа'])}, пристань и маячная башня. Живут рыбой, лодками и обслуживанием кораблей.`)
    lines.push(pick(COAST_NOTE))
  } else if (t === 'castle') {
    lines.push(`${p.name} — береговая крепость: бастионы над бухтой, береговая артиллерия и казармы Рокской пехоты. Командует ${person()}, капитан-комендант.`)
  } else if (t === 'fishing') {
    lines.push(`${p.name} — рыбацкий посёлок: десяток лодок, сушильни и коптильни, маленький маяк на дальнем конце мола. Ловят ${pick(FISH)} и ${pick(FISH)}.`)
    lines.push(`Старшина — ${person()}${chance(0.35) ? ', бывший матрос эскадры' : ''}.`)
    lines.push(pick(COAST_NOTE))
  } else if (p.coastal) {
    lines.push(`${p.name} — береговая деревня: ${pick(['сети и лодки', 'соляные ванны у моря', 'пристань с одним причалом', 'смолокурня у воды'])}. Живут рыбой и работой на порт.`)
    lines.push(`Староста — ${person()}.`)
    lines.push(pick(COAST_NOTE))
  } else {
    const o1 = pick(chance(0.5) ? ORES : FOREST), o2 = pick(ORES)
    lines.push(`${p.name} — рудничный посёлок внутри страны: ${pick(['штольни и отвалы', 'лесные делянки и лесопилка', 'карьер и плавильня', 'шахта и рудомойня'])}, ряды бараков и склад, откуда добыча уходит вниз к берегу. Добывают ${o1} и ${o2}.`)
    lines.push(`Старший — ${person()}, надсмотрщик от ${pick(['Адмиралтейства', 'Дома Доненвирен', 'Дома Хофдейк', 'Дома ван Мерен'])}.`)
    lines.push(pick(MINE_NOTE))
  }
  lines.push(`${landOf(p)}.`)
  p.description = lines.join(' ')
  n++
}

// ---------- места ----------
const place = (id, name, type, at, from, description, stateId = '', off = [14, 10]) => {
  const old = world.places.find((p) => p.id === id)
  world.places = world.places.filter((p) => p.id !== id)
  world.places.push({ id, mapId: 'world', x: Math.round(at.x) + off[0], y: Math.round(at.y) + off[1], ...(old?.innerMapId ? { innerMapId: old.innerMapId } : {}), base: { name, type, stateId, population: '', ruler: type === 'capital' ? 'Верховный адмирал Батист ван Краиланте' : '', image: '', description }, history: [], from: from == null ? null : D(from), to: null })
}
place('lore-cr-capital', 'Рокхавен', 'capital', sx(capital), null, '**Столица Лиги.** Адмиралтейство, Дом Вымпелов, Большой док, Маячный Собор и Рокхавенский рейд, где избирают Верховного адмирала. Часть города стоит над водой на сваях.', st.id, [0, 0])
place('lore-cr-admiralty', 'Адмиралтейство', 'landmark', sx(capital), 143, '**Штаб флота.** Белое здание с полом-картой всего побережья и списком выслуги адмиралов. Здесь заседает Коллегия Флагов.', '', [16, -12])
place('lore-cr-pennants', 'Дом Вымпелов', 'landmark', sx(capital), null, '**Зал пятисот знамён.** На стенах — вымпелы пятисот великих семей; здесь на выдвижение кандидата в Верховные адмиралы ставят пятьдесят подписей.', '', [-16, -12])
place('lore-cr-roads', 'Рокхавенский рейд', 'landmark', sx(capital), null, '**Место Выбора.** Весь флот выходит сюда, и корабли встают в колонны за кандидатами: до девяти дней и двадцати семи вахт.', '', [18, 14])
place('lore-cr-beacon', 'Маячный Собор', 'temple', sx(capital), null, '**Главный храм Церкви Маяка** на мысу над рейдом: белая башня с неугасимым огнём Дома Света.', '', [-18, 12])
place('lore-cr-dock', 'Большой док', 'landmark', sx(capital), 995, '**Сухой док Мадлен ван Хофдейк:** здесь строят линейные корабли нового типа и «Три сестры».', '', [0, 20])
const aur = world.provinces.find((p) => p.name === 'Аурхафен')
if (aur) place('lore-cr-blockade', 'Блокада Аурхафена', 'battle', sx(aur), 975.9, '**975.9–980.4.** Флот Лиги закрывает порты Империи, пока Совет не признает независимость. Аурхафен — главный порт Империи — стоит без торговли пять лет.', '', [-24, 24])
const tilh = byName('Тильхавен')
if (tilh) place('lore-cr-tilhaven', 'Бой у Тильхавена', 'battle', sx(tilh), 1002.5, '**1002 г.** Конвойная эскадра против пиратов Святого архипелага: двенадцать кораблей против тридцати, пираты отброшены.', '', [18, -14])
const elf = world.provinces.filter((p) => world.states.find((s) => s.id === p.owners?.at(-1)?.[1])?.base.name === 'Эльфборн' && p.coastal).sort((a, b) => a.y - b.y)[0]
if (elf) place('lore-cr-whitesails', 'Бой Белых Парусов', 'battle', sx(elf), 467.3, '**467 г.** Высадка VI Морского легиона в Эльфборне: корабли элеонов под белыми парусами прорвали Стену отчаяния. Начало перелома в Лесной войне.', '', [16, 10])

// ---------- походы эскадр ----------
world.armies = (world.armies ?? []).filter((a) => !a.id.startsWith('lore-army-cr-'))
const pt = (p, y) => { const s = sx(p); return { x: Math.round(s.x), y: Math.round(s.y), date: D(y) } }
if (capital && aur) world.armies.push({ id: 'lore-army-cr-blockade', name: 'Флот Лиги в блокаде портов Империи (975–980)', mapId: 'world', stateId: st.id, color: '#2a3f6a', waypoints: [pt(capital, 975.8), pt(aur, 976.0), pt(aur, 980.3), pt(capital, 980.6)] })
if (tilh) world.armies.push({ id: 'lore-army-cr-1002', name: 'Конвойная эскадра против пиратов (1002)', mapId: 'world', stateId: st.id, color: '#8a6a2a', waypoints: [pt(byName('Зеланте') ?? capital, 1002.3), pt(tilh, 1002.5), pt(byName('Зеланте') ?? capital, 1002.8)] })

writeFileSync(WORLD, JSON.stringify(world, null, 1))
const cnt = {}
for (const p of provs) if (p.settlement) cnt[p.settlement.type] = (cnt[p.settlement.type] ?? 0) + 1
console.log(`Крайдонианская Лига: описаний ${n}, по типам ${JSON.stringify(cnt)}`)
