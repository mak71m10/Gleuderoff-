// Королевство Болетария на карте: Бельфор (столица, бывш. Геренхайм), Балфиера (бывш. Бадельдорф), Бал-Фойен (бывш. Хольцинталь) — города;
// описания всех поселений, места (Огненный собор и Галерея Предков, три пограничных торга, угольные ямы, стычка у Тирермюнде, Огненный поход),
// походы 977–978. Запуск после temeria-detail.mjs: node scripts/boletaria-detail.mjs
import { readFileSync, writeFileSync } from 'fs'
import { BT_NAMES, STATE } from './lore/boletaria.mjs'

const WORLD = 'resources/default-world/world.json'
const world = JSON.parse(readFileSync(WORLD, 'utf8'))
const YEAR = world.calendar.months.reduce((s, m) => s + m.days, 0)
const D = (y) => Math.round((y - 1) * YEAR)
let seed = 20261121
const rnd = () => ((seed = (Math.imul(seed, 1664525) + 1013904223) >>> 0) / 4294967296)
const pick = (a) => a[Math.floor(rnd() * a.length)]
const chance = (p) => rnd() < p
const st = world.states.find((s) => s.base.name === STATE)
const admin = new Map(world.adminRegions.map((a) => [a.id, a]))

const CITIES = [
  { id: 2071, old: 'Геренхайм', name: 'Бельфор', type: 'city' },
  { id: 2023, old: 'Бадельдорф', name: 'Балфиера', type: 'city' },
  { id: 1958, old: 'Хольцинталь', name: 'Бал-Фойен', type: 'city' }
]
for (const c of CITIES) {
  const p = world.provinces.find((x) => x.id === c.id)
  if (!p) continue
  const area = admin.get(p.areaId)
  if (area?.name === `Округ ${c.old}`) area.name = `Округ ${c.name}`
  p.name = c.name
  p.settlement = { ...(p.settlement ?? { x: p.x, y: p.y }), type: c.type }
}

const provs = world.provinces.filter((p) => p.owners?.at(-1)?.[1] === st.id)
const byName = (nm) => provs.find((p) => p.name === nm)
const sx = (p) => p.settlement ?? p
const landOf = (p) => `${admin.get(p.areaId)?.name ?? ''}`
const person = (women) => `${pick(women ? BT_NAMES.women : BT_NAMES.men)} ${pick(BT_NAMES.families)}`

const LORD = { 'Округ Балфиера': 'дома Хальвейн', 'Округ Бал-Фойен': 'дома Фойен и Ордена Грифона', 'Округ Геринхайм': 'короны и дома Геринхайм' }
const FARM = ['рожь и овёс', 'лён и коноплю', 'свиней на жёлудях', 'пасеки', 'репу и капусту', 'коз и сыр']
const WOOD = ['рубят лес — но продают только Хальвейнам', 'собирают грибы и смолу', 'бьют дичь в королевских пущах по грамоте', 'режут дубовую клёпку', 'плетут корзины для угля']
const NOTE = [
  'Посреди деревни стоит Пламенник — каменный столб с жаровней; на закате священник поднимается к ней и объявляет Час Очага, и до темноты никто не говорит громко.',
  'Межевые камни здесь помечены огнём: крестьянин не может уйти со своей делянки — «Закон о межах» Огненный и вечный.',
  'В День Пепла жители высыпают золу из очагов на дорогу к Бельфору — «чтобы суд видел, что мы помним».',
  'Староста держит под замком список «живых статей» для своей деревни: сорок три запрета, из них девять — про колёса, свечи и бороды.',
  'Чужеземцев здесь не видели лет пятьдесят; когда в деревню забрёл торговец из Когалыма, его проводили до границы всей деревней — вежливо.',
  'Десятая доля каждого снопа уходит в храм: «Десятина огня» — Огненная, её не отменить.',
  'Дети играют в «Пепельный суд»: ставят в ряд палки-королей и по очереди поворачивают их к стене.',
  'На воротах вывешен знак Инквизиции — золотая маска; значит, здесь кого-то искали и не нашли.',
  'Здесь шепчутся, что серый пепел на пороге — знак Серых очагов, и сметают его до рассвета.',
  'Каждый двор обязан держать ведро воды у порога: огонь Дагота свят, но пожар — грех.'
]

let n = 0
for (const p of provs.filter((x) => x.settlement)) {
  const t = p.settlement.type
  const lord = LORD[landOf(p)] ?? 'короны'
  const lines = []
  if (p.name === 'Бельфор') {
    lines.push('Бельфор — столица Болетарии: тёмный каменный город с крутыми чёрными крышами, построенный, по преданию, Балдуином I. Над всем стоит Огненный собор с бронзовой чашей Вечного Огня под куполом и Галереей Предков, где тридцать статуй королей держат жаровни, а три стоят лицом к стене.')
    lines.push('Правит король Лотрик III Белмор. Здесь заседает Пепельный суд, в Чёрном крыле собора — Святая Инквизиция и Палата Сверки. На главной площади до сих пор чернеет круг, где в 978 г. сожгли сорок одного «собранца».')
  } else if (p.name === 'Балфиера') {
    lines.push('Балфиера — город угля и сукна: над ней всегда дым тысячи ям дома Хальвейн. Рыночная площадь чёрная от сажи, но в цеховых палатах ткут лучшее сукно королевства.')
    lines.push('Хозяйка — Угольная госпожа Хедда Хальвейн; каждый мешок угля помечен её чёрным комом. Здесь же Пламенный судья Бенно Штайн — и все знают, чей хлеб он ест.')
  } else if (p.name === 'Бал-Фойен') {
    lines.push('Бал-Фойен — рыцарский город на северо-западе: стены в три пояса, казармы Ордена Грифона и ристалище, где турнир идёт каждый месяц. Здесь куют латы, в которых не сесть на обычного коня.')
    lines.push('Великий магистр Гюнтер Фойен держит отсюда западную границу против Рейха. В 977 г. в лесах под городом прятался двор Лотрика II, а из часовни Бал-Фойена потом зажгли погасший Вечный Огонь.')
  } else if (p.name === 'Росинау') {
    lines.push('Росинау — пограничный торг у Республики, один из трёх, где чужеземцу дозволено торговать: длинные амбары, весовая палата и застава. Дом Росинау двести лет торгует здесь и двести лет считает убытки.')
  } else if (p.name === 'Тирермюнде') {
    lines.push('Тирермюнде — торг и замок маркграфов Тирер на границе с Темерией. Отсюда в 1004 г. инквизиторы пошли за беглыми еретиками через границу и встретили темерские копья.')
  } else if (p.name === 'Бадервальд') {
    lines.push('Бадервальд — третий пограничный торг, у Когалыма: здесь меняют уголь и сукно на зерно и соль, а чужих купцов на ночь запирают на постоялом дворе.')
  } else if (p.name === 'Грисинталь') {
    lines.push('Грисинталь — западная деревня у границы Рейха. С 1008 г. три соседних хутора пусты; в донесениях Ордена написано «мор», а местные запирают ставни ещё до заката.')
  } else if (t === 'city' || t === 'town') {
    lines.push(`${p.name} — городок земель ${lord}: тёмный камень, крутые крыши, Пламенник на площади и храм Огня. Живут ${pick(['сукном и шерстью', 'лесом и смолой', 'железом и кузнями', 'рынком и десятиной'])}.`)
    lines.push(`Бургомистр — ${person()}; Инквизиция держит здесь пост из трёх братьев.`)
    lines.push(pick(NOTE))
  } else if (t === 'tower' || t === 'castle') {
    lines.push(`${p.name} — сторожевая башня Ордена Грифона над лесной дорогой: каменный ствол, жаровня наверху, конюшня для тяжёлых коней. Комендант — ${person()}.`)
    lines.push('Ночью на башне горит огонь: увидел его погасшим — беги в лес.')
  } else {
    lines.push(`${p.name} — лесная деревня: ${pick(['дома из серого камня под высокими крышами', 'срубы на каменных подклетах', 'дома с чёрными сланцевыми крышами'])}, делянки и Пламенник у колодца. Здесь ${pick(WOOD)} и держат ${pick(FARM)}.`)
    lines.push(`Староста — ${person(chance(0.25))}.`)
    lines.push(pick(NOTE))
  }
  lines.push(`${landOf(p)}; земли ${lord}.`)
  p.description = lines.join(' ')
  n++
}

const place = (id, name, type, at, from, description, stateId = '', off = [14, 10], ruler = '') => {
  const old = world.places.find((p) => p.id === id)
  world.places = world.places.filter((p) => p.id !== id)
  world.places.push({ id, mapId: 'world', x: Math.round(at.x) + off[0], y: Math.round(at.y) + off[1], ...(old?.innerMapId ? { innerMapId: old.innerMapId } : {}), base: { name, type, stateId, population: '', ruler, image: '', description }, history: [], from: from == null ? null : D(from), to: null })
}
const cap = byName('Бельфор'), balf = byName('Балфиера'), foy = byName('Бал-Фойен'), ros = byName('Росинау'), tir = byName('Тирермюнде'), elm = byName('Бадервальд'), gris = byName('Грисинталь'), ver = byName('Веринштейн')
place('lore-bt-capital', 'Бельфор', 'capital', sx(cap), null, '**Столица Болетарии.** Огненный собор, Вечный Огонь, Галерея Предков и Пепельный суд.', st.id, [0, 0], 'Король Лотрик III Белмор')
place('lore-bt-cathedral', 'Огненный собор', 'temple', sx(cap), 118.2, '**Святыня Дагота.** Бронзовая чаша Вечного Огня под куполом; в боковом зале — Галерея Предков: тридцать статуй, три — лицом к стене.', '', [-16, -12])
place('lore-bt-ashsquare', 'Огненный поход', 'battle', sx(cap), 978.5, '**978.5.** Рыцари Фойенов и лесное ополчение выбивают Республику из Бельфора; на площади сожжён сорок один «собранец».', '', [16, 12])
if (balf) place('lore-bt-pits', 'Угольные ямы Хальвейнов', 'landmark', sx(balf), 541, '**Монополия угля.** Тысяча ям под Балфиерой; дым видно за три дня пути.', '', [14, -10])
if (foy) place('lore-bt-griffin', 'Замок Ордена Грифона', 'landmark', sx(foy), 300, '**Рыцарский город.** Казармы, кузни лат и ристалище Ордена Грифона.', '', [-14, 10])
if (ros) place('lore-bt-mart-ros', 'Торг Росинау', 'landmark', sx(ros), 507.1, '**Пограничный торг** с Республикой — один из трёх, где чужеземцу дозволено торговать.', '', [14, 10])
if (tir) place('lore-bt-mart-tir', 'Торг Тирермюнде', 'landmark', sx(tir), 507.1, '**Пограничный торг** с Темерией и замок маркграфов Тирер.', '', [14, -10])
if (elm) place('lore-bt-mart-elm', 'Торг Бадервальда', 'landmark', sx(elm), 507.1, '**Пограничный торг** с Когалымом: уголь и сукно на зерно и соль.', '', [14, 10])
if (tir) place('lore-bt-skirmish', 'Стычка у Тирермюнде', 'battle', sx(tir), 1004.6, '**1004.6.** Инквизиторы маркграфа Тирера переходят границу Темерии за беглыми еретиками и отступают под копьями темерской заставы.', '', [-14, 12])
if (gris) place('lore-bt-gris', 'Пустые хутора Грисинталя', 'battle', sx(gris), 1008.4, '**1008.4.** Три хутора опустели за одну ночь. Официально — мор.', '', [14, 12])

world.armies = (world.armies ?? []).filter((a) => !a.id.startsWith('lore-army-bt-'))
const pt = (p, y) => { const s = sx(p); return { x: Math.round(s.x), y: Math.round(s.y), date: D(y) } }
if (foy && cap) world.armies.push({ id: 'lore-army-bt-978', name: 'Огненный поход (978)', mapId: 'world', stateId: st.id, color: '#e07a2a', waypoints: [pt(foy, 978.1), pt(byName('Хагштейн') ?? foy, 978.3), pt(cap, 978.5)] })
if (ver && cap) world.armies.push({ id: 'lore-army-bt-republic', name: 'Республика в Бельфоре (977–978)', mapId: 'world', stateId: world.states.find((s) => s.base.name === 'Республика')?.id ?? '', color: '#a04a3a', waypoints: [pt(ver, 977.5), pt(cap, 977.6), pt(cap, 978.4)] })

writeFileSync(WORLD, JSON.stringify(world, null, 1))
const cnt = {}
for (const p of provs) if (p.settlement) cnt[p.settlement.type] = (cnt[p.settlement.type] ?? 0) + 1
console.log(`Болетария: описаний ${n}, по типам ${JSON.stringify(cnt)}`)
