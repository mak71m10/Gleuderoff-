let n = 0
for (const p of provs.filter((x) => x.settlement)) {
  const t = p.settlement.type
  const lines = []
  if (p.name === 'Антсла') {
    lines.push('Антсла — столица Эрэдамства Олекохт: бревенчатый город под белым храмом на скале.')
    lines.push(SPECIAL.Антсла)
  } else if (SPECIAL[p.name]) {
    const kind = t === 'temple' ? 'храм' : t === 'town' ? (p.name === 'Элва' ? 'город' : 'городок') : t === 'city' ? 'город' : 'село'
    lines.push(`${p.name} — ${kind} Олекохта.`)
    lines.push(SPECIAL[p.name])
    if (t !== 'temple') lines.push(pick(NOTE))
  } else if (t === 'town') {
    lines.push(`${p.name} — «полугород» Олекохта: бревенчатые дома в два яруса, площадь для фургонов трупп, храм Элу с Тулакролом во дворе. Живут ${pick(CROP)}.`)
    lines.push(pick(NOTE))
    lines.push(`Старшина — ${person(chance(0.4))}.`)
  } else {
    const vl = chance(0.25)
    lines.push(`${p.name} — ${t === 'fishing' ? 'рыбацкое село у воды' : 'село'}${vl ? ' валлинов' : ''}: ${pick(['низкие срубы под крутыми крышами, дым из каждой трубы до весны', 'дворы вокруг колодца и общей коптильни', 'дома вдоль ручья, у околицы молодой Тулакрол', 'длинный дом старосты и амбар на сваях от волков'])}; живут ${pick(CROP)}.`)
    lines.push(`Староста — ${vl ? vallin() : person(chance(0.35))}.`)
    lines.push(pick(NOTE))
  }
  if (border.includes(p)) lines.push('Через село идёт тракт на Уунааш; с 1008 г. путники ходят по нему только днём и только вдвоём.')
  lines.push(`${circleOf(p)}, ${landOf(p)}; элуины${provs.indexOf(p) % 4 === 0 ? ' и валлины' : ''}.`)
  p.description = lines.join(' ')
  n++
}

