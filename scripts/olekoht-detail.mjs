// Запуск после harnmark-detail.mjs: node scripts/olekoht-detail.mjs
import { readFileSync, writeFileSync } from 'fs'
import { STATE } from './lore/olekoht.mjs'

const WORLD = 'resources/default-world/world.json'
const world = JSON.parse(readFileSync(WORLD, 'utf8'))
const YEAR = world.calendar.months.reduce((s, m) => s + m.days, 0)
const D = (y) => Math.round((y - 1) * YEAR)
let seed = 20261121
const rnd = () => ((seed = (Math.imul(seed, 1664525) + 1013904223) >>> 0) / 4294967296)
const pick = (a) => a[Math.floor(rnd() * a.length)]
const chance = (p) => rnd() < p
const st = world.states.find((s) => s.base.name === STATE)
const admin = new Map(world.adminRegions.map((a) => [a.id, a]))

// переименования по канону автора: столица Антсла, второй город Элва
export const OL_CITIES = [['Талиурит', 'Антсла'], ['Нээль', 'Элва']]
for (const [old, nw] of OL_CITIES) {
  const p = world.provinces.find((x) => x.owners?.at(-1)?.[1] === st.id && (x.name === old || x.name === nw))
  if (!p) continue
  const area = admin.get(p.areaId)
  if (area && area.name === `Круг ${old}`) area.name = `Круг ${nw}`
  p.name = nw
  if (nw === 'Антсла') p.settlement.type = 'city'
}

const provs = world.provinces.filter((p) => p.owners?.at(-1)?.[1] === st.id)
const byName = (nm) => provs.find((p) => p.name === nm)
const sx = (p) => p.settlement ?? p
const landOf = (p) => admin.get(admin.get(p.areaId)?.parentId)?.name ?? ''
const circleOf = (p) => admin.get(p.areaId)?.name ?? ''
const pm = new Map(world.provinces.map((p) => [p.id, p]))
const uu = world.states.find((s) => s.base.name === 'Уунааш')
const border = provs.filter((p) => p.neighbors.some((n) => pm.get(n)?.owners?.at(-1)?.[1] === uu?.id))

