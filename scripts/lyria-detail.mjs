// Протекторат Лирия (Эллирия) на карте: Лирия (столица, бывш. Хеймельштейн), Айзанх (бывш. Бадельштадт), Медиволанум (бывш. Штайнштейн);
// горные крепости на дворфийских основаниях, террасы, каменоломни; описания всех поселений, места (Стена Трёх Тысяч, Форум Имён, Поле Тишины), поход именных воинов.
// Запуск после temeria-detail.mjs: node scripts/lyria-detail.mjs
import { readFileSync, writeFileSync } from 'fs'
import { STATE } from './lore/lyria.mjs'

const WORLD = 'resources/default-world/world.json'
const world = JSON.parse(readFileSync(WORLD, 'utf8'))
const YEAR = world.calendar.months.reduce((s, m) => s + m.days, 0)
const D = (y) => Math.round((y - 1) * YEAR)
let seed = 20261111
const rnd = () => ((seed = (Math.imul(seed, 1664525) + 1013904223) >>> 0) / 4294967296)
const pick = (a) => a[Math.floor(rnd() * a.length)]
const chance = (p) => rnd() < p
const st = world.states.find((s) => s.base.name === STATE)
const admin = new Map(world.adminRegions.map((a) => [a.id, a]))

const CITIES = [
  { id: 1565, old: 'Хеймельштейн', name: 'Лирия', type: 'city' },
  { id: 1701, old: 'Бадельштадт', name: 'Айзанх', type: 'city' },
  { id: 1773, old: 'Штайнштейн', name: 'Медиволанум', type: 'town' }
]
for (const c of CITIES) {
  const p = world.provinces.find((x) => x.id === c.id)
  const area = admin.get(p.areaId)
  if (area?.name === `Округ ${c.old}`) area.name = `Округ ${c.name}`
  p.name = c.name
  p.settlement = { ...(p.settlement ?? { x: p.x, y: p.y }), type: c.type }
}

const provs = world.provinces.filter((p) => p.owners?.at(-1)?.[1] === st.id)
const byName = (nm) => provs.find((p) => p.name === nm)
const sx = (p) => p.settlement ?? p
const landOf = (p) => admin.get(p.areaId)?.name ?? ''
const FIRST = ['Гней', 'Луций', 'Марк', 'Публий', 'Секст', 'Квинт', 'Тит', 'Авл', 'Гай', 'Децим']
const GENS = ['Корнелий', 'Валерий', 'Фабий', 'Эмилий', 'Октавий', 'Аний', 'Туллий', 'Помпоний', 'Ливий', 'Сульпиций']
const person = () => `${pick(FIRST)} ${pick(GENS)}`

const CROP = ['виноградные террасы', 'оливковые рощи', 'овец и козий сыр', 'каштаны и мёд', 'ячмень на ступенях склона', 'горные пасеки']
const ROCK = ['мрамор', 'серый камень', 'железную руду', 'серебро', 'медную руду']
const NOTE = [
  'Над дверью каждого дома висит табличка с именем рода; у безымянных она пустая, и никто не решается её заполнить.',
  'В День Тишины деревня не произносит ни слова: даже петухов ловят и кормят зерном, чтобы не кричали.',
  'Ранней весной на полях находят дворфийские гвозди и пряжки; их складывают в ящик у часовни и не продают.',
  'Староста держит список «табличек» деревни: сколько Имён светится, сколько погасло и кому о них надо сообщить.',
  'Дети играют в «Сбор»: делятся на Сотни, спорят и голосуют камешками; безымянных не берут — они наблюдают.',
  'Рядом проходит старая дворфийская дорога, ровнее любой лирийской; её плиты не трескаются, и никто не знает, чем их скрепляли.',
  'Здесь не говорят «рудник», а говорят «старая работа»: штольни помнят не людей.',
  'В часовне Культа Имён горит одна свеча за всех погасших табличек деревни.'
]

let n = 0
for (const p of provs.filter((x) => x.settlement)) {
  const t = p.settlement.type
  const lines = []
  if (p.name === 'Лирия') {
    lines.push('Лирия — столица Протектората и «Эллирия» для тех, кто помнит: город белого мрамора на пологом склоне над долиной. В центре — Форум Имён, где стоит Стена Трёх Тысяч — длинная мраморная стена с тремя тысячами табличек, светящихся ночью, как поле звёзд.')
    lines.push('Здесь живёт Герцог-Протектор Гай VII Юний Темпест, заседает Сбор Сотен и стоит Храм Имён. Над крышами висят красные знамёна с золотым орлом, а на каждом углу — маленькая табличка с именем владельца дома.')
  } else if (p.name === 'Айзанх') {
    lines.push('Айзанх — торговый город у перекрёстка долинных дорог: колоннады рынков, амбары, винные погреба и дворцы Сервилиев и Помпониев. Живут вином, мрамором и посредничеством между Эллирией и соседями.')
    lines.push('Здесь больше всего Вписанных и безымянных; на рынке по утрам стоят вдоль Стены безымянные с гладкими камнями на шее и молча наблюдают.')
  } else if (p.name === 'Медиволанум') {
    lines.push('Медиволанум — город-молчание. Здесь в Первую эпоху Гиббелин IX вырезал последних дворфов и гномов Эллириума. На месте резни — Поле Тишины: широкая ровная площадь без единого дерева, где в День Тишины никто не говорит.')
    lines.push('Хранитель поля — Старый Тит; в городе живут рудокопы Каменной Сотни и жрецы Культа Имён. Каждую весну на поле находят то гвоздь, то пряжку, то зуб, и жрецы кладут находку в ящик, который никто не открывает.')
  } else if (p.name === 'Висингард') {
    lines.push('Висингард — руины на лесистом холме: Республика сожгла здесь амбары в 977 г., и пожарище так и осталось. Лирийцы говорят, что на таких местах нельзя строить, пока не наберётся достаточно Имён.')
  } else if (t === 'castle') {
    lines.push(`${p.name} — крепость на дворфийских основаниях: нижние ярусы выложены гладким камнем без швов, а верхние добавили лирийцы. Здесь стоит Нагорная застава или рудничная контора. Комендант — ${person()}.`)
    lines.push(pick(NOTE))
  } else if (t === 'town') {
    lines.push(`${p.name} — городок Протектората: форум с колоннадой, рынок и Дом Имён, где в стене выбиты таблички местных родов. Живут ${pick(['вином и маслом', 'мрамором и камнем', 'торговлей по долине', 'выпасом и сыром'])}.`)
    lines.push(`Куратор Имён — ${person()}; жрец Культа Имён раз в год проверяет, светятся ли таблички.`)
    lines.push(pick(NOTE))
  } else if (t === 'tower') {
    lines.push(`${p.name} — дозорная башня на дворфийской кладке; сигнальный огонь виден до Лирии. Командует ${person()}.`)
  } else if (p.terrain === 4 || p.terrain === 5 || p.terrain === 6) {
    lines.push(`${p.name} — горная деревня: дома из серого камня с плоскими черепичными крышами, штольни «старой работы» и пастбища. Добывают ${pick(ROCK)} и держат ${pick(CROP)}.`)
    lines.push(`Староста — ${person()}.`)
    lines.push(pick(NOTE))
  } else {
    lines.push(`${p.name} — долинная деревня: белёные дома с красной черепицей, террасы и колодец с мраморной резьбой. Выращивают ${pick(CROP)}.`)
    lines.push(`Староста — ${person()}${chance(0.3) ? ', бывший именной воин' : ''}.`)
    lines.push(pick(NOTE))
  }
  lines.push(`${landOf(p)}.`)
  p.description = lines.join(' ')
  n++
}

const place = (id, name, type, at, from, description, stateId = '', off = [14, 10], ruler = '') => {
  const old = world.places.find((p) => p.id === id)
  world.places = world.places.filter((p) => p.id !== id)
  world.places.push({ id, mapId: 'world', x: Math.round(at.x) + off[0], y: Math.round(at.y) + off[1], ...(old?.innerMapId ? { innerMapId: old.innerMapId } : {}), base: { name, type, stateId, population: '', ruler, image: '', description }, history: [], from: from == null ? null : D(from), to: null })
}
const cap = byName('Лирия'), aiz = byName('Айзанх'), med = byName('Медиволанум'), eren = byName('Эренвальд'), stein = byName('Эберенштейн'), vis = byName('Висингард')
place('lore-ly-capital', 'Лирия', 'capital', sx(cap), null, '**Столица Протектората.** Форум Имён со Стеной Трёх Тысяч, дворец Герцога-Протектора, Храм Имён и зал Сбора Сотен.', st.id, [0, 0], 'Герцог-Протектор Гай VII Юний Темпест')
place('lore-ly-wall', 'Стена Трёх Тысяч', 'landmark', sx(cap), 96.1, '**Святыня Лирии.** Мраморная стена с тремя тысячами табличек; светятся только те, за которыми жив потомок. Обратная сторона закрыта кладкой.', '', [-16, -12])
place('lore-ly-forum', 'Форум Имён', 'landmark', sx(cap), null, '**Площадь Сбора.** Раз в год здесь собираются тридцать Сотен, каждая у своего столба.', '', [16, -12])
if (med) {
  place('lore-ly-silence', 'Поле Тишины', 'landmark', sx(med), 95.4, '**Место резни.** Здесь Гиббелин IX вырезал последних дворфов и гномов Эллириума. В День Тишины на поле никто не говорит.', '', [14, 12])
}
if (aiz) place('lore-ly-servilii', 'Дом Сервилиев', 'landmark', sx(aiz), 997.2, '**Торговый дворец.** Вписанные откупщики держат здесь счёт всей торговли Протектората.', '', [-14, 12])
if (eren) place('lore-ly-pass', 'Нагорная застава', 'landmark', sx(eren), 993, '**Перевал над Харнмарком.** Здесь стоит Нагорная стража; в 993 г. спор о перевале не дошёл до войны.', '', [14, -10])
if (stein) place('lore-ly-shafts', 'Старые штольни', 'landmark', sx(stein), 17.5, '**Работа дворфов.** Глубокие штольни и залы Эллириума, которыми рудничная коллегия пользуется до сих пор.', '', [-14, -10])
if (vis) place('lore-ly-visingard', 'Пожарище Висингарда', 'landmark', sx(vis), 977.1, '**977.1.** Республика сожгла здесь амбары и объявила табличек «рабскими».', '', [12, -12])

world.armies = (world.armies ?? []).filter((a) => !a.id.startsWith('lore-army-ly-'))
const pt = (p, y) => { const s = sx(p); return { x: Math.round(s.x), y: Math.round(s.y), date: D(y) } }
if (cap && eren) world.armies.push({ id: 'lore-army-ly-977', name: 'Именные воины Гая VI (977–978)', mapId: 'world', stateId: st.id, color: '#d8b84a', waypoints: [pt(cap, 977.9), pt(eren, 978.1), pt(cap, 978.3)] })

writeFileSync(WORLD, JSON.stringify(world, null, 1))
const cnt = {}
for (const p of provs) if (p.settlement) cnt[p.settlement.type] = (cnt[p.settlement.type] ?? 0) + 1
console.log(`Лирия: описаний ${n}, по типам ${JSON.stringify(cnt)}`)
