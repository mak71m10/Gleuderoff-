// Королевство Редания на карте: Тревенбург (бывш. Касберг) — столица, Нойбрюк (бывш. Вединведель) — мост в девять пролётов,
// Оксенау (бывш. Нейинштадт) — Бычий брод; пять великих переправ, мостовые будки с белыми пропусками; описания поселений, места, походы.
// Названия автора из «Ведьмака» (Третогор, Новиград, Оксенфурт) заменены по его разрешению.
// Запуск после kagia-detail.mjs: node scripts/redania-detail.mjs
import { readFileSync, writeFileSync } from 'fs'
import { STATE } from './lore/redania.mjs'

const WORLD = 'resources/default-world/world.json'
const world = JSON.parse(readFileSync(WORLD, 'utf8'))
const YEAR = world.calendar.months.reduce((s, m) => s + m.days, 0)
const D = (y) => Math.round((y - 1) * YEAR)
let seed = 20261122
const rnd = () => ((seed = (Math.imul(seed, 1664525) + 1013904223) >>> 0) / 4294967296)
const pick = (a) => a[Math.floor(rnd() * a.length)]
const st = world.states.find((s) => s.base.name === STATE)
const admin = new Map(world.adminRegions.map((a) => [a.id, a]))

const CITIES = [
  { id: 1495, old: 'Касберг', name: 'Тревенбург', type: 'city' },
  { id: 1418, old: 'Вединведель', name: 'Нойбрюк', type: 'city' },
  { id: 1496, old: 'Нейинштадт', name: 'Оксенау', type: 'town' }
]
for (const c of CITIES) {
  const p = world.provinces.find((x) => x.id === c.id)
  if (!p) continue
  const area = admin.get(p.areaId)
  if (area?.name === `Округ ${c.old}`) area.name = `Округ ${c.name}`
  p.name = c.name
  p.settlement = { ...(p.settlement ?? { x: p.x, y: p.y }), type: c.type }
}

const provs = world.provinces.filter((p) => p.owners?.at(-1)?.[1] === st.id)
const byName = (nm) => provs.find((p) => p.name === nm)
const sx = (p) => p.settlement ?? p
const landOf = (p) => admin.get(p.areaId)?.name ?? ''
const FIRST = ['Гюнтер', 'Хайнц', 'Ульрих', 'Лоренц', 'Себастьян', 'Ансгар', 'Элизабет', 'Ханна', 'Вальбурга', 'Иоахим', 'Тобиас', 'Ида']
const LAST = ['Фэр', 'Мюллер', 'Брюкнер', 'Шиффер', 'Ведер', 'Бах', 'Флёсснер', 'Зейлер', 'Ротмунд', 'Кранц']
const person = () => `${pick(FIRST)} ${pick(LAST)}`

const NOTE = [
  'У въезда — мостовая будка с медной печатью: белый пропуск здесь спрашивают даже у гнома-лудильщика, который ходит через мост тридцать лет.',
  'В первый день каждого месяца староста читает на мосту Клятву месяца вслух — короля здесь нет, но клятву слушают все.',
  'На перилах моста зарубки: по одной на каждую Звёздную ночь. Их четыре, и одна обведена углём.',
  'Мельничный колокол звонит, когда Мостовой закрывает переправу; дети знают этот звон раньше церковного.',
  'Паромщик берёт с людей грош, с нелюдей — три, и половину отдаёт общине, не пересчитывая.',
  'Дети играют в «звезду»: стоят на мостках и кричат «вижу!»; кто крикнул третьим — тот король на суде.',
  'Старухи вешают над дверью жестяную звезду с обрезанным хвостом — чтобы звёзды «падали мимо».',
  'У брода стоит каменная тумба с выбитым глазом и мостом — знак Мостовой инквизиции 951 г.; её не трогают и не чистят.'
]
const CROP = ['рожь и сено с заливных лугов', 'мельничный помол для соседей', 'лён и красильную вайду', 'рыбу с запруд', 'хмель на склонах']

let n = 0
for (const p of provs.filter((x) => x.settlement)) {
  const t = p.settlement.type
  const lines = []
  if (p.name === 'Тревенбург') {
    lines.push('Тревенбург — столица Редании на Королевском мосту: город стоит по обоим берегам, а мост — его главная улица с лавками и мельницами прямо на быках. На правом берегу — замок Реденов с белой башней, на левом — Звёздный собор с открытым к небу куполом.')
    lines.push('Пять раз в год король выходит на середину моста и приносит Клятву месяца пятерым Мостовым. Мельница Ирены Мюльнер мелет зерно для двора, а будка белых пропусков стоит у самых ворот замка.')
  } else if (p.name === 'Нойбрюк') {
    lines.push('Нойбрюк — торговый город у каменного моста в девять пролётов, построенного Империей в 420 г. На предмостье — склады, весы на цепях и рынок на трёх языках; на мосту — пошлина, будка белых пропусков и колокол Паромного братства.')
    lines.push('Здесь правит Мостовой Варин Фергер и торгует Шарлотта Ланц. Третий год у моста стоит обоз дварфа Брокка Гранитоборца с Высокогорья: ему пропуск дали, его возчикам — нет.')
  } else if (p.name === 'Оксенау') {
    lines.push('Оксенау — городок у Бычьего брода и мельничной плотины: красильни, синие ручьи от вайды и запах сырой шерсти. Брод мелкий, и Мостовой Оксенау меняет сторону так же легко, как его переходят.')
    lines.push('Гнездо Дома Фалков; отсюда родом королева Эрменгарда, мельникова дочь, ставшая женой графа.')
  } else if (p.name === 'Грюнингард') {
    lines.push('Грюнингард — замок над ущельем с подъёмным мостом: при Империи здесь сидела Мостовая инквизиция, сейчас — Палата белых пропусков и капитан Ханно Штег. В 962 г. у моста в давке погибли сорок девять дварфов.')
    lines.push('Здесь двенадцать лет жил в изгнании снятый король Радвальд I и здесь умер. Слепой магистр Кляйн живёт в башне и узнаёт людей по шагу.')
  } else if (p.name === 'Тальерхайм') {
    lines.push('Тальерхайм — деревня паромщиков у переправы к Павильону Грёз. Паром — плот на канате через реку; в 992 г. его сожгли, нынешний построен на деньги, которых у деревни не было.')
    lines.push('Мостовой Рутгер Фэр возит музыкантов, послов и ящики; по вечерам с того берега слышна музыка. ' + pick(NOTE))
  } else if (t === 'castle') {
    lines.push(`${p.name} — замок речной стражи над бродом. Комендант — ${person()}.`)
    lines.push(pick(NOTE))
  } else if (t === 'town') {
    lines.push(`${p.name} — городок у моста: рынок на предмостье, мостовая будка и мельница на быке. Мытарь — ${person()}.`)
    lines.push(pick(NOTE))
  } else {
    lines.push(`${p.name} — ${p.terrain === 6 ? 'деревня на сухом берегу, где река уходит в песок; колодцы и паромные мостки' : 'деревня в речной долине: мостки, мельница и заливные луга'}. Живут ${pick(CROP)}.`)
    lines.push(`Староста — ${person()}.`)
    lines.push(pick(NOTE))
  }
  lines.push(`${landOf(p)}; живут реданцы.`)
  p.description = lines.join(' ')
  n++
}

const place = (id, name, type, at, from, description, stateId = '', off = [14, 10], ruler = '') => {
  const old = world.places.find((p) => p.id === id)
  world.places = world.places.filter((p) => p.id !== id)
  world.places.push({ id, mapId: 'world', x: Math.round(at.x) + off[0], y: Math.round(at.y) + off[1], ...(old?.innerMapId ? { innerMapId: old.innerMapId } : {}), base: { name, type, stateId, population: '', ruler, image: '', description }, history: [], from: from == null ? null : D(from), to: null })
}
const cap = byName('Тревенбург'), nb = byName('Нойбрюк'), ox = byName('Оксенау'), gr = byName('Грюнингард'), th = byName('Тальерхайм')
place('lore-rd-capital', 'Тревенбург', 'capital', sx(cap), null, '**Столица Редании.** Королевский мост, замок Реденов, Звёздный собор.', st.id, [0, 0], 'Король Радвальд II Реденский')
place('lore-rd-cathedral', 'Звёздный собор', 'landmark', sx(cap), 983.8, '**Собор Звёздной книги.** Купол открыт к небу; здесь сидит звездочёт Звёздного суда.', '', [-16, -12])
if (nb) place('lore-rd-ninespan', 'Мост в девять пролётов', 'landmark', sx(nb), 420.2, '**Нойбрюк.** Имперский каменный мост: путь с Высокогорья и Кулагона; пошлина и белые пропуска.', '', [16, -10])
if (gr) place('lore-rd-962', 'Давка у Грюнингарда', 'battle', sx(gr), 962.3, '**962.** Мостовая стража поворачивает обоз дварфов; сорок девять погибших.', '', [12, 12])
if (th) place('lore-rd-ferry', 'Тальерхаймский паром', 'landmark', sx(th), 992.9, '**Переправа к Павильону Грёз.** Сожжён в 992 г., отстроен; Мостовой получает жалованье Павильона.', '', [12, -10])
if (ox) place('lore-rd-ford', 'Бычий брод', 'landmark', sx(ox), null, '**Оксенау.** Мелкий брод и мельничная плотина; Мостовой Оксенау куплен королём к Звёздной ночи 1010 г.', '', [-12, 10])

world.armies = (world.armies ?? []).filter((a) => !a.id.startsWith('lore-army-rd-'))
const pt = (p, y) => { const s = sx(p); return { x: Math.round(s.x), y: Math.round(s.y), date: D(y) } }
if (cap && gr && th) world.armies.push({ id: 'lore-army-rd-992', name: 'Сторонники Радвальда I у парома (992)', mapId: 'world', stateId: st.id, color: '#c83a3a', waypoints: [pt(gr, 992.85), pt(cap, 992.87), pt(th, 992.9), pt(gr, 992.95)] })
if (cap && nb) world.armies.push({ id: 'lore-army-rd-979', name: 'Мостовые общины изгоняют комиссаров (979)', mapId: 'world', stateId: st.id, color: '#4a8ac8', waypoints: [pt(nb, 979.2), pt(cap, 979.4)] })

writeFileSync(WORLD, JSON.stringify(world, null, 1))
const cnt = {}
for (const p of provs) if (p.settlement) cnt[p.settlement.type] = (cnt[p.settlement.type] ?? 0) + 1
console.log(`Редания: описаний ${n}, по типам ${JSON.stringify(cnt)}`)
