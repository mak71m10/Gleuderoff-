// Эльфборн на карте: описания всех поселений, гнёзда двенадцати Домов, места (Серебряная Ива, Чертог Счётчиков,
// Поющие Камни Стены Отчаяния, Пролом, Сожжённая роща, поля войны 976–981).
// Запуск после kulagon-detail.mjs: node scripts/elfborn-detail.mjs
import { readFileSync, writeFileSync } from 'fs'
import { STATE } from './lore/elfborn.mjs'

const WORLD = 'resources/default-world/world.json'
const world = JSON.parse(readFileSync(WORLD, 'utf8'))
const YEAR = world.calendar.months.reduce((s, m) => s + m.days, 0)
const D = (y) => Math.round((y - 1) * YEAR)
let seed = 20261114
const rnd = () => ((seed = (Math.imul(seed, 1664525) + 1013904223) >>> 0) / 4294967296)
const pick = (a) => a[Math.floor(rnd() * a.length)]
const chance = (p) => rnd() < p
const st = world.states.find((s) => s.base.name === STATE)
const admin = new Map(world.adminRegions.map((a) => [a.id, a]))

const provs = world.provinces.filter((p) => p.owners?.at(-1)?.[1] === st.id)
const byName = (nm) => provs.find((p) => p.name === nm)
const sx = (p) => p.settlement ?? p
const landOf = (p) => admin.get(p.areaId)?.name ?? ''

// Гнёзда Домов: город → [Дом, что там стоит]
const SEAT = {
  Рильмиэль: ['Миринэль', 'оружейные дворы и белая башня магов, где куют крылатые шлемы'],
  Линаватар: ['Лаурэндил', 'усадьба среди золотых полей, крытая медной черепицей'],
  Нэармиэль: ['Исилвен', 'тихий серый дом послов с голубятней на крыше'],
  Лаинватар: ['Таурендил', 'зелёный зал под живыми буками, где хранят луки рощи'],
  Мэоралос: ['Фаэлин', 'длинный дом из чёрных брёвен, на воротах — волчьи черепа'],
  Ваэльватар: ['Аилин', 'открытая лечебница: в ней нет ни одной двери'],
  Силастэ: ['Ундоме', 'дом на сваях над заливом, с раковиной над входом'],
  Валаватар: ['Элендор', 'чёрная башня, где окна открывают только ночью'],
  Кэнариэль: ['Сангвэль', 'зелёный замок, в который Высшие не заходят без нужды'],
  Теанвен: ['Каранор', 'северный замок Стражи Стены и главный арсенал'],
  Ауреэльватар: ['Вастар', 'казармы ветеранов Братств и поле, где они получили обещание земли']
}
const SPECIAL = {
  Мэоралос: 'Рядом чернеет Сожжённая роща: в 978 г. её подожгли Дикие эльфы, и там до сих пор не растёт трава.',
  Ауреэльватар: 'У ворот — курган Боя у Ауреэльватара (977): первое большое сражение Войны Голых Ветвей.',
  Теанвен: 'Стены замка в заплатах после осады 979 г., когда Братства требовали отменить рабство.',
  Аненастэ: 'Развалины крепости, разбитой Империей при Проломе Стены (467); сюда водят новобранцев Каранора.',
  Тиарриэль: 'Развалины старой рощи-храма; дубы срублены легионами в Лесную войну.'
}
const FN = ['Аэрон', 'Гэлмир', 'Каэлин', 'Таэрил', 'Элоин', 'Финдол', 'Лаэрос', 'Мирдан', 'Наурэль', 'Сэлдир']
const FW = ['Аэрин', 'Лаэрэ', 'Нимэль', 'Таэра', 'Эльвинэ', 'Иримэ', 'Силмэ', 'Финуэль']
const HN = ['Том', 'Мартин', 'Эйрик', 'Ганс', 'Анна', 'Мерет', 'Лиса', 'Ян']
const person = (w) => `${pick(w ? FW : FN)} ${pick(['из рощи', 'Светлый', 'Тихий', 'Седой', 'Стрелок', 'Певец корней', 'Ясный', 'Лист'])}`
const NOTE = [
  'В центре растёт отводок Серебряной Ивы; раз в год, в Ночь Листопада, к нему приходят Счётчики и смотрят на листья.',
  'Полуэльфы здесь носят серую ленту на рукаве: по Закону о Третьем Сорте у них нет земли и нет ветви в Книге.',
  'У опушки стоит камень обета: кто нарушит обет духам рощи, оставляет здесь дань — хлеб, мёд или кровь.',
  'Здесь не рубят живых деревьев: дома строят из бурелома, а сушняк собирают дети по осени.',
  'По вечерам поют «Корневую песнь»: низкий напев, от которого, говорят, крепнут корни.',
  'Местные боятся соли: солонки держат под замком и не сыплют её на землю.',
  'Над дверями висят сухие листья — по одному на каждую засохшую ветвь; люди считают их сами, не веря Счётчикам.',
  'Ночью у околицы слышны шаги: здесь проходят патрули Каранора, и полуэльфов без пропуска уводят в долговой труд.',
  'Полуэльфы в деревне шепчутся о «Привое» и рисуют мелом привитую ветку на заборах — и смывают к утру.'
]
const CROP = ['мёд и воск', 'орехи и ягоды', 'луки и стрелы из тиса', 'лён и ткань', 'вино из дикого винограда', 'целебные травы', 'дичь и меха', 'рыбу и жемчуг']

let n = 0
for (const p of provs.filter((x) => x.settlement)) {
  const t = p.settlement.type
  const lines = []
  if (p.name === 'Анорланте') {
    lines.push('Анорланте — столица и корень страны: город из светлого дерева, арок и мостков, выросший вокруг Серебряной Ивы. Ива стоит на главной площади, ствол в три обхвата, двенадцать ветвей — двенадцать Домов Книги Побегов.')
    lines.push('Здесь Престол Ивы, Чертог Счётчиков Листвы, храм Дома Света и гнездо Дома Аэлтар. Правит Страж Корня Иллендель Лаурэндил. Полуэльфы города живут за ручьём и носят серые ленты.')
  } else if (SEAT[p.name]) {
    const [h, what] = SEAT[p.name]
    lines.push(`${p.name} — гнездо Дома ${h}: ${what}.`)
    if (SPECIAL[p.name]) lines.push(SPECIAL[p.name])
    lines.push(`Управитель — ${person(chance(0.4))}.`)
    lines.push(pick(NOTE))
  } else if (SPECIAL[p.name]) {
    lines.push(`${p.name} — ${t === 'ruins' ? 'руины' : 'поселение'}. ${SPECIAL[p.name]}`)
    lines.push(pick(NOTE))
  } else if (t === 'temple') {
    lines.push(`${p.name} — роща-храм Дома Света: белые колонны среди деревьев, жрецы поют Иве утренний гимн. Сюда приходят приносить обеты.`)
    lines.push(`Настоятель — ${person(chance(0.5))}.`)
  } else if (t === 'castle' || t === 'tower') {
    lines.push(`${p.name} — ${t === 'tower' ? 'сторожевая башня' : 'замок'} Каранора: гарнизон лесных стрелков, сигнальный огонь на крыше.`)
    lines.push(`Комендант — ${person()}.`)
  } else if (t === 'port') {
    lines.push(`${p.name} — гавань с белыми лодками и деревянными причалами; живут ${pick(CROP)}. Чужие корабли досматривает стража: соли на берег не пускают.`)
    lines.push(`Старшина гавани — ${chance(0.25) ? `${pick(HN)}, полуэльф с серой лентой` : person(chance(0.4))}.`)
    lines.push(pick(NOTE))
  } else if (t === 'town') {
    lines.push(`${p.name} — городок под кронами: дома на сваях и мостки между деревьями, рынок под навесом из ветвей. Живут ${pick(CROP)}.`)
    lines.push(`Управитель — ${person(chance(0.4))}.`)
    lines.push(pick(NOTE))
  } else if (t === 'ruins') {
    lines.push(`${p.name} — заросшие руины эльфийской усадьбы: Лесная война 451–488 гг. оставила здесь только корни и камень.`)
  } else {
    lines.push(`${p.name} — ${t === 'fishing' ? 'рыбацкая деревня у воды' : 'деревня в чаще'}: ${pick(['дома среди корней старых буков', 'низкие дома, крытые дёрном', 'хижины на помостах над землёй', 'круг домов вокруг родника'])}; живут ${pick(CROP)}.`)
    lines.push(chance(0.35) ? `Здесь больше полуэльфов, чем эльфов; старшина — ${pick(HN)}, в серой ленте.` : `Старшина — ${person(chance(0.3))}.`)
    lines.push(pick(NOTE))
  }
  lines.push(`${landOf(p)}.`)
  p.description = lines.join(' ')
  n++
}

const place = (id, name, type, at, from, description, stateId = '', off = [14, 10], ruler = '') => {
  const old = world.places.find((p) => p.id === id)
  world.places = world.places.filter((p) => p.id !== id)
  world.places.push({ id, mapId: 'world', x: Math.round(at.x) + off[0], y: Math.round(at.y) + off[1], ...(old?.innerMapId ? { innerMapId: old.innerMapId } : {}), base: { name, type, stateId, population: '', ruler, image: '', description }, history: [], from: from == null ? null : D(from), to: null })
}
world.places = world.places.filter((p) => !p.id.startsWith('lore-el-stone-'))
const cap = byName('Анорланте')
place('lore-el-capital', 'Анорланте', 'capital', sx(cap), null, '**Корень страны.** Город светлого дерева вокруг Серебряной Ивы; Престол Ивы, Чертог Счётчиков и храм Дома Света.', st.id, [0, 0], 'Страж Корня Иллендель Лаурэндил')
place('lore-el-willow', 'Серебряная Ива', 'landmark', sx(cap), 981, '**Живой престол.** Двенадцать ветвей — двенадцать Домов Книги Побегов. Пока зелены пять, Страж Корня законен. В Ночь Серебряных Ив (980) дерево едва не сгорело.')
place('lore-el-counters', 'Чертог Счётчиков', 'landmark', sx(cap), 981, '**Чертог Листвы.** Здесь жрецы Дома Света в Ночь Листопада считают знаки: три знака за год — ветвь сохнет. Здесь же хранят Книгу Побегов.', '', [-14, 10])
place('lore-el-night', 'Ночь Серебряных Ив', 'battle', sx(cap), 980, '**980.** Братства и Дикие сошлись у Ивы; роща вокруг горела всю ночь, Ива уцелела. Через год заключён Мир Двенадцати Ветвей.', '', [14, -12])
const mo = byName('Мэоралос'), au = byName('Ауреэльватар'), te = byName('Теанвен')
if (mo) place('lore-el-meoralos', 'Сожжённая роща', 'landmark', sx(mo), 978, '**978.** Дикие эльфы Дома Фаэлин сожгли рощу духов у Мэоралоса — сделали со своими то, что делала Империя. Трава здесь не растёт до сих пор.', '', [-16, 12])
if (au) place('lore-el-aurel', 'Бой у Ауреэльватара', 'battle', sx(au), 977, '**977.** Первое большое сражение Войны Голых Ветвей: Братства разбили войско Высших.', '', [16, 12])
if (te) place('lore-el-teanven', 'Осада Теанвена', 'battle', sx(te), 979, '**979.** Революционные Братства осаждают замок: требуют отмены рабства и раздела земли. Каранор держит стены до мира.', '', [16, -12])

// Стена Отчаяния: цепь Поющих Камней поперёк севера, с запада на восток
const WALL = [[6050, 2215], [6150, 2235], [6250, 2225], [6350, 2240], [6440, 2230], [6530, 2215], [6620, 2225], [6710, 2245], [6800, 2235], [6870, 2225]]
const BREACH = 4
WALL.forEach(([x, y], i) => {
  if (i === BREACH) return
  place(`lore-el-stone-${i + 1}`, `Поющий Камень ${['I', 'II', 'III', 'IV', 'V', 'VI', 'VII', 'VIII', 'IX', 'X'][i]}`, 'landmark', { x, y }, 40,
    '**Стена Отчаяния.** Высокий серый камень с вырезанными листьями; в ветер он гудит. Чужак, прошедший между камнями, теряет надежду; эльф с Листом проходит спокойно. Камни держит Дом Каранор; сила Стены идёт от корней Ивы.', '', [0, 0])
})
place('lore-el-breach', 'Пролом', 'ruins', { x: WALL[BREACH][0], y: WALL[BREACH][1] }, 467.3, '**467.** Здесь VI Морской легион Империи, высаженный кораблями под белыми парусами, разбил Поющий Камень и прошёл вглубь страны. Камень так и не поставили заново: в 976 г. север вернули, но Стена молчит в этом месте.', '', [0, 0])

writeFileSync(WORLD, JSON.stringify(world, null, 1))
console.log(`Эльфборн: описаний ${n}, мест ${world.places.filter((p) => p.id.startsWith('lore-el-')).length}`)
