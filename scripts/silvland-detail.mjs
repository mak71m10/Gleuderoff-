// Сильвленд на карте: описания всех 50 поселений, пять Матерей-деревьев, гнёзда Домов, места (Южные Заставы, Рощи).
// Запуск после elfborn-detail.mjs: node scripts/silvland-detail.mjs
import { readFileSync, writeFileSync } from 'fs'
import { STATE } from './lore/silvland.mjs'

const WORLD = 'resources/default-world/world.json'
const world = JSON.parse(readFileSync(WORLD, 'utf8'))
const YEAR = world.calendar.months.reduce((s, m) => s + m.days, 0)
const D = (y) => Math.round((y - 1) * YEAR)
let seed = 20261116
const rnd = () => ((seed = (Math.imul(seed, 1664525) + 1013904223) >>> 0) / 4294967296)
const pick = (a) => a[Math.floor(rnd() * a.length)]
const chance = (p) => rnd() < p
const st = world.states.find((s) => s.base.name === STATE)
const admin = new Map(world.adminRegions.map((a) => [a.id, a]))

const provs = world.provinces.filter((p) => p.owners?.at(-1)?.[1] === st.id)
const byName = (nm) => provs.find((p) => p.name === nm)
const sx = (p) => p.settlement ?? p
const landOf = (p) => admin.get(p.areaId)?.name ?? ''

// Города Матерей: город -> [Мать, месяц, Дом, что видно]
const MOTHER = {
  Нэнадор: ['Нэнадор', 'Ячори', 'Тавэлин', 'Мать Нэнадор стоит посреди площади: ствол в шесть обхватов, крона выше городских башен. Под корнями — Чертог Урожаев и Корневой Ряд, где сильва совещаются, но не решают'],
  Аурелаватар: ['Аурелаватар', 'Фраул', 'Аурелан', 'Мать Аурелаватар растёт во дворе замка; ветви у неё широкие, плоды мелкие и жёлтые'],
  Эленнор: ['Эленнор', 'Алпрас', 'Вэйлин', 'Мать Эленнор обнесена оградой из живых лиан: плоды у неё крупные, их выкупает Дом Вэйлин и отправляет церкви Дома Света'],
  Исенриэль: ['Исенриэль', 'Лаций', 'Исенвэль', 'Мать Исенриэль на вид молода и невысока; на пне рядом видны следы топоров 463 года. Корни обожжены ордынским огнём 1001 года'],
  Риорриэль: ['Риорриэль', 'Драгос', 'Риорэн', 'Мать Риорриэль огромна, но осенью не роняет листьев; к нижним ветвям на лианах подвязаны плоды, и Дом Риорэн не пускает сюда чужих']
}
const SEAT = {
  Аэасвен: ['Аурелан', 'замок береговых Застав: серая башня, сигнальный огонь, склад солёной рыбы'],
  Нэарэссе: ['Тавэлин', 'сторожевая башня над бухтой; с неё видно паруса Республики за сорок миль']
}
const SPECIAL = {
  Саиналос: 'Здесь штаб Южных Застав: капитан Ориэль Риорэн держит рубеж с Ордой, на частоколе висят ордынские щиты.',
  Лоанмиэль: 'Порт, заложенный Республике Шеша в 1004 г. под заём на посадку; чужаки живут только на Белом дворе у причала, дальше опушки им нужен «чужой лист» Опекуна.',
  Мэанэссе: 'Второй залоговый порт Республики; чужой двор огорожен колышками, склады подписаны по-шешски, а плоды отгружают в закрытых бочках.',
  Лоналос: 'У околицы рощица, сожжённая Ордой в 1001 г.; молодые деревья посажены ряд за рядом по числу погибших.',
  Анильланте: 'Тут живёт больше сильва, чем эльфов; над калиткой висят пучки веток по числу родившихся, а на плече у каждого сильва выжжена метка корня.',
  Нэильватар: 'У околицы разбит лагерь Эльфборна: Ива-Страж забирает здесь соки по договору 998 г.'
}
const FN = ['Аэрон', 'Гэлмир', 'Каэлин', 'Таэрил', 'Элоин', 'Финдол', 'Лаэрос', 'Мирдан', 'Наурэль', 'Сэлдир']
const FW = ['Аэрин', 'Лаэрэ', 'Нимэль', 'Таэра', 'Эльвинэ', 'Иримэ', 'Силмэ', 'Финуэль']
const SN = ['Рябина', 'Липа', 'Вяз', 'Кизил', 'Орешник', 'Шиповник', 'Лещина', 'Черёмуха', 'Боярышник', 'Дубок']
const person = (w) => `${pick(w ? FW : FN)} ${pick(['из рощи', 'Светлый', 'Тихий', 'Седой', 'Ягодный', 'Певец корней', 'Ясный', 'Листок'])}`
const NOTE = [
  'В центре стоит малый отросток Матери и белый Шнуровой столб: на нём висят шнуры Опекуна, и каждый знает, сколько на них узлов.',
  'Сильва тут рождаются из плодов у корней: раз в месяц один, и им нарекают имя по дереву.',
  'Над дверями висят связки красных ягод: так отмечают, что в доме живёт сильва; у опушки стоит столб Стражи Опушек, где чужаку велено ждать проводника.',
  'Чужих не пускают дальше опушки без «чужого листа»; ночевать им велено на колодах у столба, а нож и железо оставить страже.',
  'Здесь делают сок-клей и смолу из коры, кремнёвые скребки и рогатые луки: железа в доме нет, его считают чужим.',
  'Часть плодов с каждого дерева уходит эльфам-Опекунам по повинности; сильва, не сдавший урожай, остаётся без метки корня и без воды из родника.',
  'Каждый дом — живое дерево с дуплом: дверь и окна вырезаны в стволе, лестница из корней; топор к ним не прикладывают.',
  'По вечерам поют «Песнь Корня»: низкий напев, под который, говорят, крепнут корни.',
  'Местные не любят огня: костры жгут только на камне и сразу заливают водой.',
  'Здесь помнят Падалицу 1003 года: тогда весь урожай собрали в одной корзине и считали вслух.',
  'Вдоль дороги растут яблони, посаженные на плоды Матери; их урожай считают отдельно от оброка Матерей.'
]
const CROP = ['мёд и воск', 'орехи и ягоды', 'яблоки и грушу', 'лён и ткань', 'ягодное вино', 'целебные травы', 'дичь и меха', 'рыбу и жемчуг']

let n = 0
for (const p of provs.filter((x) => x.settlement)) {
  const t = p.settlement.type
  const lines = []
  if (MOTHER[p.name]) {
    const [tree, month, house, what] = MOTHER[p.name]
    lines.push(p.name === 'Нэнадор'
      ? `Нэнадор — столица Сильвленда: город-лес на корнях Великой Матери: каждый дом — живое дерево с дуплом. ${what}.`
      : `${p.name} — город Матери ${tree}, месяц ${month}. ${what}.`)
    lines.push(`Опекун — Дом ${house}. ${p.name === 'Нэнадор' ? 'Здесь живёт Хранитель Опушки Сэлиндэ Аурелан, у корней стоит Шнуровой столб страны, а в Тихий лес собирается Совет Опекунов.' : 'У корней стоит Шнуровой столб: здесь Опекун вяжет узлы-запреты при трёх свидетелях.'}`)
  } else if (SEAT[p.name]) {
    const [h, what] = SEAT[p.name]
    lines.push(`${p.name} — ${what}; под рукой Дома ${h}.`)
    if (SPECIAL[p.name]) lines.push(SPECIAL[p.name])
    lines.push(`Комендант — ${person(chance(0.3))}.`)
  } else if (t === 'port') {
    lines.push(`${p.name} — гавань с деревянными пристанями; живут ${pick(CROP)}.`)
    lines.push(SPECIAL[p.name] ?? pick(NOTE))
    lines.push(`Старшина гавани — ${person(chance(0.4))}.`)
  } else if (t === 'town') {
    lines.push(`${p.name} — городок-лес: дома — деревья с дуплами, мостки между кронами, рынок на ветвях. Живут ${pick(CROP)}.`)
    lines.push(`Управитель — ${person(chance(0.4))}.`)
    lines.push(pick(NOTE))
  } else {
    lines.push(`${p.name} — ${t === 'fishing' ? 'рыбацкая деревня у воды' : 'деревня в чаще'}: ${pick(['дома-деревья среди старых буков, жильё в дуплах', 'дубы с дверями в стволах, лестницы из корней', 'липы-дома на мостках из ветвей', 'круг деревьев-домов вокруг родника'])}; живут ${pick(CROP)}.`)
    if (SPECIAL[p.name]) lines.push(SPECIAL[p.name])
    lines.push(chance(0.4) ? `Старшина — сильва по имени ${pick(SN)}.` : `Старшина — ${person(chance(0.3))}.`)
    if (!SPECIAL[p.name]) lines.push(pick(NOTE))
  }
  lines.push(`${landOf(p)}.`)
  p.description = lines.join(' ')
  n++
}

const place = (id, name, type, at, from, description, stateId = '', off = [14, 10], ruler = '') => {
  const old = world.places.find((p) => p.id === id)
  world.places = world.places.filter((p) => p.id !== id)
  world.places.push({ id, mapId: 'world', x: Math.round(at.x) + off[0], y: Math.round(at.y) + off[1], ...(old?.innerMapId ? { innerMapId: old.innerMapId } : {}), base: { name, type, stateId, population: '', ruler, image: '', description }, history: [], from: from == null ? null : D(from), to: null })
}
world.places = world.places.filter((p) => !p.id.startsWith('lore-sv-'))
const cap = byName('Нэнадор')
place('lore-sv-capital', 'Нэнадор', 'capital', sx(cap), null, '**Столица.** Город на корнях Матери Нэнадор: Шнуровой столб с пятью шнурами запретов, Чертог Урожаев, совещательный Корневой Ряд сильвы и Совет Опекунов. Здесь живёт Хранитель Опушки Сэлиндэ Аурелан: десять узлов на шнуре.', st.id, [0, 0], 'Хранитель Круга Сэлиндэ Аурелан')
const MT = {
  Нэнадор: ['Ячори', 'Тавэлин'], Аурелаватар: ['Фраул', 'Аурелан'], Эленнор: ['Алпрас', 'Вэйлин'], Исенриэль: ['Лаций', 'Исенвэль'], Риорриэль: ['Драгос', 'Риорэн']
}
for (const [nm, [month, house]] of Object.entries(MT)) {
  const pr = byName(nm)
  if (!pr) continue
  place(`lore-sv-tree-${nm.toLowerCase()}`, `Мать ${nm}`, 'landmark', sx(pr), 12,
    `**Великая Мать, месяц ${month}.** Дерево в 120–150 м, Опекун — Дом ${house}. Каждый год в свой месяц даёт плоды, из которых рождаются сильва; пока Мать жива, её Опекун вправе вязать запреты.${nm === 'Риорриэль' ? ' Подходить к ней запрещено узлом Дома Риорэн.' : ''}`, '', [nm === 'Нэнадор' ? -14 : 14, -12])
}
const sa = byName('Саиналос'), ise = byName('Исенриэль'), lo = byName('Лоналос')
if (sa) place('lore-sv-south', 'Южные Заставы', 'landmark', sx(sa), 1001, '**Южный рубеж.** Частокол и сторожевые вышки против Орды, после набега 1001 г. Эльфы-лучники и сильва-копейщики; командует Ориэль Риорэн.', '', [16, 12])
if (ise) place('lore-sv-raid', 'Набег на рощу Исенриэль', 'battle', sx(ise), 1001.4, '**1001.** Орда прорвалась к Исенриэли и подожгла рощу; сильва Ольха вопреки запрету вывела раненых, стража её не тронула, и шнур Опекуна Каэлиса развязался. Мать молчала три года.', '', [-16, 12])
if (cap) place('lore-sv-post', 'Шнуровой столб', 'landmark', sx(cap), 981, '**Где вяжут запреты.** Белый ствол мёртвого тиса у корней Нэнадор, на нём пять лубяных шнуров в цвет Домов-Опекунов. Узел вяжут при трёх свидетелях; упавший шнур висит пустым до Ячори. Только Вязальщица Лаэрэль поднимается к нему.', '', [16, 14])
if (cap) place('lore-sv-bow', 'Лук Ольхи', 'battle', sx(cap), 1010.9, '**1010.** Сильва Ольха прошла с рогатым луком через ворота Нэнадора при страже: запрет Хранителя «сильва не держит оружия вне дня боя» нарушен открыто. Стража медлит; если кары не будет до Ячори 1011 г., шнур Сэлиндэ Аурелан развяжется целиком.', '', [-18, 14])
if (lo) place('lore-sv-grove', 'Новая роща', 'landmark', sx(lo), 1002, '**Посадка.** После набега здесь высадили молодые деревья по числу погибших; на каждом — лента с именем.', '', [-14, 12])

writeFileSync(WORLD, JSON.stringify(world, null, 1))
console.log(`Сильвленд: описаний ${n}, мест ${world.places.filter((p) => p.id.startsWith('lore-sv-')).length}`)
