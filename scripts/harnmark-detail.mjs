let n = 0
for (const p of provs.filter((x) => x.settlement)) {
  const t = p.settlement.type
  const lines = []
  if (p.name === 'Орельберг') {
    lines.push(`${p.name} — столица Княжества Харнмарк, город на излучине реки: ратуша, белая башня Дома Харн и Дом Колыбелей у Нижних ворот.`)
    lines.push(SPECIAL[p.name])
  } else if (SPECIAL[p.name] && SEAT_NAME.has(p.name)) {
    const kind = t === 'port' ? 'порт' : t === 'town' ? 'город' : 'сельцо'
    lines.push(`${p.name} — ${kind} Харнмарка.`)
    lines.push(SPECIAL[p.name])
    lines.push(pick(NOTE))
  } else if (t === 'port') {
    lines.push(`${p.name} — гавань с каменной пристанью; живут ${pick(CROP)}.`)
    lines.push(SPECIAL[p.name] ?? pick(NOTE))
  } else if (t === 'town') {
    lines.push(`${p.name} — город Харнмарка: каменные дома под красной черепицей, рыночная площадь, церковь Дома Света. Живут ${pick(CROP)}.`)
    lines.push(SPECIAL[p.name] ?? pick(NOTE))
    lines.push(`Бургомистр — ${person(chance(0.3))}.`)
  } else {
    lines.push(`${p.name} — ${t === 'fishing' ? 'рыбацкая деревня у воды' : 'деревня'}: ${pick(['дома из камня и дерева под красной черепицей, церковь с шатровой колокольней', 'длинный двор старосты и кузница у перекрёстка', 'три десятка дворов вокруг мельницы и общего колодца', 'дома вдоль речной дороги, у околицы межевой камень'])}; живут ${pick(CROP)}.`)
    if (SPECIAL[p.name]) lines.push(SPECIAL[p.name])
    lines.push(`Староста — ${person(chance(0.25))}.`)
    if (!SPECIAL[p.name]) lines.push(pick(NOTE))
  }
  lines.push(`${landOf(p)}.`)
  p.description = lines.join(' ')
  n++
}

